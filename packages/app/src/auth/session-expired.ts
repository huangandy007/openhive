/**
 * 「有个出口吃到 401」的**报信口**（2026-10-10 用户下达的第 2 件：会话过期后没有重新登录的出口）。
 *
 * ## 缺的是什么（真栈实测，不是推演）
 *
 * 会话在页面开着的时候失效 ⇒ 点「新建」⇒ 横幅说得对（「登录已过期，请重新登录」），
 * 而**界面一动不动**：登录页 0、工作台 1、URL 停在 `/`。同一条坏 cookie **冷加载**却出得来
 * 登录页 ⇒ **判据没坏，缺的是第二次探查**。
 *
 * 结构上的原因：`probeSession`（`gateway.ts`）是全仓**唯一**那道「我现在有身份吗」的判断，
 * 而它的生产调用者只有一个——`AuthGate`。401 则在**十个**外呼落点上被遇到（实测 `grep` + 逐点读，
 * 只有五处认得出它），每一个都够不到唯一能处理它的那一层。所以消息需要一条路：**出口 → 门**。
 *
 * ## 为什么是模块级订阅表，不是 context
 *
 * 发消息的人是**任意层的普通函数**（`project/openhive-fetch.ts` 的 `trySend`，被九个客户端调用，
 * 其中一些纯粹是数据处理、跑在被 `AuthGate` 盖住的子树里但压根不在组件作用域里）。
 * context 只给组件读；要塞进去就得让九个调用点各自把回调一路传下来——那正是本件要躲开的东西。
 *
 * 代价是**取消订阅得自己记得**（`session-context.ts` 那条老话：模块级接缝不会随子树生死）。
 * 用法只有一处（`AuthGate`），退订写在 `onCleanup` 里；测试同理（`auth-gate.test.tsx` 的
 * `afterEach` 收宿主时一并收掉）。
 *
 * ## 与 `workspace/current-user.ts` 的分工
 *
 * 那个是**状态**（当前是谁，读的人多），这个是**事件**（发生了一件「没身份了」，听的人只有一个）。
 * 状态用信号（`createSignal`：读的人要跟着变），事件用订阅表（没有人需要「当前值」，
 * 硬造一个「上一次 401 是几点」的状态只会多出一个要复位的字段）。
 *
 * ## 喊一声**不等于**「一定没身份了」
 *
 * 一次 401 可能只是一条链上的偶发（内核重启、会话刚好在这一次往返中被顶掉）。所以订阅方
 * **必须去重探一次**、以重探的结论为准，不能听见就跳登录页——`auth-gate.test.tsx` 那条
 * 「重探说『你还是你』⇒ 留在工作台」的对照用例就是为这件事存在的。
 *
 * ## 谁来喊，谁**不许**喊
 *
 * `trySend` 是唯一该喊的地方（fork 那几条裸路由都过它）。⚠️ **身份那条链不许喊**：
 * `@/auth/gateway` 的 `probeSession` / `login` / `logout` 走自己的 `roundTrip`，**不经过 `trySend`**
 * ——这是必须的，「登录被拒」也是 401，那条链若也喊，一次输错密码就会把重探引成回环。
 */

/** 听一声「有出口吃到 401」。返回退订函数（**调用方负责退订**：模块级接缝自己收不回来）。 */
export function onSessionExpired(listener: () => void): () => void {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

/**
 * 喊一声。**不返回值、不抛**：调用方是外呼底座，喊完照常走自己的结论（该报「取不到」还报）。
 *
 * 同时刻多个出口都吃 401 ⇒ 会喊多次 ⇒ 订阅方重探多次。**不加去重守卫**：多探几次得到的是同一个
 * 结论（`GET /me` 一条本机同源请求），而一个「别重复探」的守卫要多存一份状态、多一个要复位的
 * 时刻，为省几次本地请求不值。真要收，收在订阅方（门那边知道自己在探）。
 */
export function markSessionExpired(): void {
  // 直接遍历 Set：`Set` 的迭代器允许在遍历中退订（本处唯一的听众不退订，`AuthGate` 的回调只重探）。
  // 刻意**不**复制一份再遍历（`#002-06` 那条「不留没被逼出来的代码」）：副本要防的是
  // 「回调里再订阅一个」——今天没有第二个订阅方，真出现时该改的是「谁在订阅」，不是这行。
  for (const listener of listeners) listener()
}

const listeners = new Set<() => void>()
