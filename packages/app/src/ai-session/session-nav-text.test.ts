import { describe, expect, test } from "bun:test"
import { 可读片段, 索引标签, 预览文本, 预览上限 } from "./session-nav-text"

/**
 * 索引轨要显示的**两样文字**的规格（2026-10-14，用户报「不能在大段会话里快速找回自己问过的
 * 那句话及其回答」；照 DeepSeek 的做法做）。
 *
 * 这两样是：**索引面板里每行那一句**（`索引标签`）与**鼠标停在某行时弹出的那段**（`预览文本`）。
 *
 * ## ⚠️ 本文件钉的是「从哪块文本里取」，而不是「怎么排视觉」
 *
 * 视觉（短横多长、面板多宽、往左还是往右弹）在真栈上量，happy-dom 没有布局引擎（`#005-07`）。
 * 这一份只管一件事：**给用户的这几个字，是不是他自己打的那几个字**。
 *
 * ## ⚠️ 与仓里另外两份「取文本」判据的关系（`#002-06` / `#003-05`）
 *
 * 仓库里已经有两处「从消息片段里找 user 文本」了，本模块**必须**和其中**一份**同形、且明确
 * 地和另一份**不同形**：
 *
 * | 落点 | 判据 | 与本模块的关系 |
 * |---|---|---|
 * | `packages/session-ui/src/components/message-part.tsx:1198`（**用户那个气泡**渲染的就是它） | `find(p => p.type === "text" && !p.synthetic)` —— 第一个非 synthetic 的 text 块 | **必须逐字同形**：索引里显示的那句话，就是气泡上那句话 |
 * | `packages/app/src/utils/prompt.ts:43` `textPartValue` | `filter(!synthetic && !ignored)` 后取**最长**的一块 | **故意不同形**：那是「撤销时把原话填回输入框」，要的是全量原文；这里要的是气泡上展示的那一块 |
 *
 * 三份判据各服一个目的，这不是「同一个判断写了两份」——**但索引这一份是在镜像上游那一份**，
 * 上游若改了那行，这一行要跟着改（`#003-05`：镜像跨层判据要写成能被上游变更惊醒的样子）。
 */
const 文本 = (text: string, 额外: Partial<可读片段> = {}): 可读片段 => ({ type: "text", text, ...额外 })

describe("索引标签（索引面板里那一行字）", () => {
  test("取用户那句话的第一行（后头的行不进索引）", () => {
    expect(索引标签([文本("帮我把这份纪要改成三段\n第二行不要")])).toBe("帮我把这份纪要改成三段")
  })

  test("开头是空行 ⇒ 跳过空行，取第一句有字的", () => {
    expect(索引标签([文本("\n\n  帮我看一下\n后面还有")])).toBe("帮我看一下")
  })

  test("⚠️ 取的是**第一个非 synthetic** 的文本块（与用户气泡渲染的是同一块）", () => {
    expect(索引标签([文本("内核塞进去的", { synthetic: true }), 文本("我自己打的")])).toBe("我自己打的")
  })

  test("只剩工具块 / 文件块（用户那句没留下文本）⇒ undefined（该行不给标签）", () => {
    expect(索引标签([{ type: "tool" }, { type: "file" }])).toBe(undefined)
  })

  test("片段还没到（undefined）⇒ undefined", () => {
    expect(索引标签(undefined)).toBe(undefined)
  })

  test("片段是空的 ⇒ undefined", () => {
    expect(索引标签([])).toBe(undefined)
  })

  test("文本块只有空白 ⇒ undefined（不给用户一个空格当索引）", () => {
    expect(索引标签([文本("   \n\t ")])).toBe(undefined)
  })

  test("⚠️ win32 的换行（\\r\\n）⇒ 行尾不留车符（本机粘贴进来的话常带它，看不见但会让断言莫名地红）", () => {
    expect(索引标签([文本("帮我看一下\r\n后面还有")])).toBe("帮我看一下")
  })

  test("首行很长 ⇒ 原样返回；截断交给 CSS（JS 再截一次会出现两个省略号）", () => {
    const 长 = "很长很长的一句话".repeat(30)
    expect(索引标签([文本(`${长}\n第二行`)])).toBe(长)
  })
})

describe("预览文本（鼠标停在某一行时弹出的那段）", () => {
  test("短句原样给，换行保留（这一处不是只取首行）", () => {
    expect(预览文本([文本("第一行\n第二行")])).toBe("第一行\n第二行")
  })

  test("首尾空白修剪掉（气泡结尾那个空行不该算进字数）", () => {
    expect(预览文本([文本("\n\n  帮我看看  \n\n")])).toBe("帮我看看")
  })

  test("超过上限 ⇒ 截到上限 ＋ 省略号", () => {
    expect(预览文本([文本("甲".repeat(预览上限 + 1))])).toBe("甲".repeat(预览上限) + "…")
  })

  test("⚠️ 恰好等于上限 ⇒ 不加省略号（边界；差一个字的两条判据都得在）", () => {
    expect(预览文本([文本("乙".repeat(预览上限))])).toBe("乙".repeat(预览上限))
  })

  test("取的是与标签**同一块**文本（第一个非 synthetic 的块）", () => {
    expect(预览文本([文本("内核塞进去的", { synthetic: true }), 文本("我自己打的")])).toBe("我自己打的")
  })

  test("没有文本块 ⇒ undefined", () => {
    expect(预览文本([{ type: "tool" }])).toBe(undefined)
  })

  test("片段还没到 ⇒ undefined", () => {
    expect(预览文本(undefined)).toBe(undefined)
  })
})
