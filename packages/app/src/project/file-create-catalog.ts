/**
 * 「新建文件」弹窗的类型清单（013 · T3，用户 2026-11-16 裁定）：
 * 从 012 的「一排类型胶囊」换成「9 个大类、每类一行（左类名 / 右后缀）」；
 * 2026-11-16 二轮又去掉了勾选框（选中只靠蜜蜂金边框）。
 *
 * ## 后缀不许在这里再写一遍
 *
 * 清单与视图注册表认的是**同一批**后缀（`@/center/file-type-extensions`，013 · T2）。
 * 若在这里另写一份字面量，改注册表漏改清单**不报错、不变红**，用户会建出双击打不开的文件
 * （`LEARNINGS #002-06`）。因此这里只做「引用常量 / 从中筛出子集」，不新造后缀。
 *
 * ## 两个「子集」的裁定（spec §4 裁定 1）
 *
 * - **文档只列 `.docx`**：`.doc` 是 legacy 二进制，后端没有可靠模板生成器；`.doc` 既有文件
 *   仍由注册表打开。
 * - **表格只列 `.xlsx` / `.csv`**：`.xls` 同上。
 *
 * 两处用 `filter` 从注册表常量里**筛**，而不是另写字面量数组——这样「注册表里还有 .doc/.xls」
 * 这件事在源码里只有一个出处，筛掉的项也在注释里写明原因。
 */
import {
  PDF扩展名,
  代码扩展名,
  关系图扩展名,
  图片扩展名,
  图文扩展名,
  思维导图扩展名,
  网页扩展名,
  文档扩展名,
  表格扩展名,
} from "@/center/file-type-extensions"

export interface 新建大类 {
  readonly 名称: string
  readonly 后缀们: readonly string[]
  /** 默认折叠的只有「代码」——一屏列不下，且多数民警不建代码文件。 */
  readonly 默认折叠?: boolean
}

/** 大类顺序是用户 2026-11-16 逐条确认的，改动前先看 spec §2。 */
export const 新建大类: readonly 新建大类[] = [
  {
    名称: "文档",
    // 注册表里还有 `.doc`，但它是 legacy 二进制、没有可靠模板生成器 ⇒ 不能建（spec §4 裁定 1）。
    后缀们: 文档扩展名.filter((后缀) => 后缀 === ".docx"),
  },
  {
    名称: "表格",
    // 注册表里还有 `.xls`，同上不可建；`.csv` 纯文本、可直接写。
    后缀们: 表格扩展名.filter((后缀) => 后缀 !== ".xls"),
  },
  { 名称: "图文", 后缀们: 图文扩展名 },
  { 名称: "关系图", 后缀们: 关系图扩展名 },
  { 名称: "思维导图", 后缀们: 思维导图扩展名 },
  { 名称: "PDF", 后缀们: PDF扩展名 },
  { 名称: "图片", 后缀们: 图片扩展名 },
  { 名称: "网页", 后缀们: 网页扩展名 },
  { 名称: "代码", 后缀们: 代码扩展名, 默认折叠: true },
]

/**
 * 名字已带同后缀（**大小写不敏感**）⇒ 原样；否则追加。
 *
 * 从 `file-create-types.ts` 迁来（013 · T3），行为逐字不变，只把参数从「类型对象」换成后缀字符串。
 * 带**其它**后缀（如 `.md`）按名字处理 ⇒ `张三.md.hgraph`——与契约 ui.md §7 的裁定一致。
 */
export function 补类型后缀(name: string, 后缀: string): string {
  return name.toLowerCase().endsWith(后缀.toLowerCase()) ? name : `${name}${后缀}`
}
