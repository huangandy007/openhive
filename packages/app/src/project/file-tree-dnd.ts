/**
 * 同树拖拽的落点判据（纯函数：无 DOM、无信号、零依赖）。
 *
 * ## 为什么单独一个文件
 *
 * 它不读组件状态、也不碰 DOM，却要能被单测直接钉住；`file-tree-model.ts` 是 005「空目录那一支」
 * 的专用模块（单导出 `buildProjectFileTreeModel`），把拖拽判据塞进去会污染它的职责
 * （`docs/superpowers/specs/2026-10-15-file-tree-multi-select-move-design.md` §4 勘误）。
 * 新文件对上游**零冲突面**（第一号约束）。
 *
 * ## 路径写法
 *
 * 与仓里其余各处同一套：`/` 分隔、无前后斜杠、**项目根是 `""`**（同 `file-tree.tsx` 的
 * `落点()`）。不另立一套切分规则（`LEARNINGS #006-23`）。
 */

/** 路径它**现在**住在哪个目录里。顶层 ⇒ `""`（项目根）。 */
const 父目录 = (path: string) => {
  const index = path.lastIndexOf("/")
  return index === -1 ? "" : path.slice(0, index)
}

/**
 * 这一批源能不能落到 `目标` 目录上。三条不许：
 *
 * ① 目标是**某个源自己**（拖到自己身上）
 * ② 目标以「某个源 ＋ `/`」开头（拖进**自己的子孙**）
 * ③ **源现在就住在目标里**（`父目录(源) === 目标`）——搬过去等于什么都没发生
 *
 * 多个源里**有一个不合法 ⇒ 整体不行**：一次手势在磁盘上只该发生一件事，
 * 「三个里两个搬进了第三个」几乎不是任何人的本意（spec §9 取舍 5）。
 *
 * ⚠️ ③ 写的是 `父目录(源)` 而**不是** `落点(源)`：`落点()` 对**目录**回它自己（它要回答的是
 * 「往它这儿建东西该建在哪」），于是「一个顶层目录拖到项目根」这种「它本来就在那儿」的情形
 * 会**漏掉**。`父目录` 对文件与目录是同一条规则（都是 dirname），恰是 ③ 要说的事
 * （spec §5.2 写的是 `落点(源) === 目标`，此处按它那句话的**意思**修正常见的读法——spec 里
 * 要的是「它现在就在那儿」，不是「落点等于目标」）。
 */
export function 能落到(源们: readonly string[], 目标: string): boolean {
  if (源们.length === 0) return false
  for (const 源 of 源们) {
    if (目标 === 源) return false
    if (目标.startsWith(`${源}/`)) return false
    if (父目录(源) === 目标) return false
  }
  return true
}
