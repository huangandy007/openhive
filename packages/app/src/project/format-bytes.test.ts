import { describe, expect, test } from "bun:test"
import { 格式化字节 } from "./format-bytes"

/**
 * 全仓唯一的人读字节格式（2026-10-18）。
 *
 * 动因是实测出来的**同一份数字两个读法**：窗口 `文件大小()` 出 `5.9 MB`、窄条 `格式()` 出
 * `6 MiB`。两处都在说「已用多少」，而用户看到的是两个不同的数。
 *
 * 口径：MB / GB（十进制单位词，不是 MiB / GiB）＋ **1 位小数**——与系统文件管理器一致，
 * 对民警不出现「GiB」这种行话。
 */
describe("格式化字节", () => {
  test("GB 档：3.4 GB、10.0 GB", () => {
    expect(格式化字节(3.4 * 1024 ** 3)).toBe("3.4 GB")
    expect(格式化字节(10 * 1024 ** 3)).toBe("10.0 GB")
  })

  test("MB 档保留 1 位小数（旧窄条这里是 0 位 ⇒ 「6 MiB」）", () => {
    expect(格式化字节(5.9 * 1024 ** 2)).toBe("5.9 MB")
    expect(格式化字节(6 * 1024 ** 2)).toBe("6.0 MB")
  })

  test("KB 档同样 1 位小数", () => {
    expect(格式化字节(1.2 * 1024)).toBe("1.2 KB")
  })

  test("不足 1 KB 原样给字节数", () => {
    expect(格式化字节(512)).toBe("512 B")
  })

  test("两边边界不跳档：1023 B / 1 KB / 1 MB / 1 GB", () => {
    expect(格式化字节(1023)).toBe("1023 B")
    expect(格式化字节(1024)).toBe("1.0 KB")
    expect(格式化字节(1024 ** 2)).toBe("1.0 MB")
    expect(格式化字节(1024 ** 3)).toBe("1.0 GB")
  })
})
