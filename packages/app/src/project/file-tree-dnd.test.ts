import { describe, expect, test } from "bun:test"
import { 能落到 } from "./file-tree-dnd"

/**
 * 「这一批能不能落到那儿」——同树拖拽的**唯一**判据。
 *
 * 路径写法与本仓其余各处同一套（`/` 分隔、无前后斜杠、项目根是 `""`，
 * 见 `file-tree.tsx` 的 `落点()` 与 `normalizeFileTreeV2Path`）——不在这里另立一套切分规则
 * （`LEARNINGS #006-23`：同一目录多种写法，前提破功时两处都不报错）。
 */
describe("能落到", () => {
  test("落到一个别的目录 ⇒ 可以", () => {
    expect(能落到(["资料/话单.csv"], "档案")).toBe(true)
  })

  test("落到项目根（\"\"）⇒ 可以", () => {
    expect(能落到(["资料/话单.csv"], "")).toBe(true)
  })

  test("拖到自己身上 ⇒ 不行（目录）", () => {
    expect(能落到(["资料"], "资料")).toBe(false)
  })

  test("拖进自己的子孙 ⇒ 不行", () => {
    expect(能落到(["资料"], "资料/8·17")).toBe(false)
  })

  test("它现在就在那儿 ⇒ 不行（文件）", () => {
    expect(能落到(["资料/话单.csv"], "资料")).toBe(false)
  })

  test("它现在就在那儿 ⇒ 不行（顶层目录，目标是项目根）", () => {
    expect(能落到(["资料"], "")).toBe(false)
  })

  /**
   * `资料/8` 与 `资料/80`：**前缀相同、但不是子孙**。
   * 少了那个 `/`，`startsWith("资料/8")` 就会把这一条也拦掉 ⇒ 这条用例就是那个分隔符的守卫。
   */
  test("同前缀但不是子孙 ⇒ 可以", () => {
    expect(能落到(["资料/8"], "资料/80")).toBe(true)
  })

  test("多源里只有一个非法 ⇒ 整体不行（不做「能搬的先搬」）", () => {
    expect(能落到(["资料/话单.csv", "档案"], "资料")).toBe(false)
  })

  test("多源全部合法 ⇒ 可以（含一个目录）", () => {
    expect(能落到(["资料/话单.csv", "档案/旧件.csv"], "归档")).toBe(true)
  })

  test("空的一批 ⇒ 不行（起拖时已保证非空，这里是兜底的反面）", () => {
    expect(能落到([], "档案")).toBe(false)
  })
})
