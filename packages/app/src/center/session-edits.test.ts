import { beforeEach, describe, expect, test } from "bun:test"
import {
  会话改过,
  当前重载代,
  归一事件路径,
  清会话改过,
  清空会话改过,
  触发重载,
  记会话改过,
} from "./session-edits"

/**
 * 登记处的规格（2026-10-13，用户实报「AI 改了中栏打开的文件，界面一点动静都没有」）。
 *
 * 这一份测的是**纯状态**：谁的路径被记过、谁没被记过、清得掉清不掉。它不去碰中栏的
 * tab / 视图——「记过之后 tab 上真出现圆点」「点一下真换新内容」在 `tab-bar.test.tsx` /
 * `center-content.test.tsx` 各自的文件里测（那是两件事，别在这一份里合着测，
 * `LEARNINGS #005-46`：一条用例塞两三件事时，后面那几件的守护者身份是没被证明的）。
 *
 * ⚠️ **这是模块级的一份状态**（同 `views/reading-size.ts` 的 `阅读字号`）：跨用例活着，
 * 所以每条用例开头必须 `清空会话改过()`，否则上一条留下的圆点会飘到下一条里。
 */
describe("会话改过的登记处（中栏「这份文件被 AI 改过」的单一真相源）", () => {
  beforeEach(() => {
    清空会话改过()
  })

  test("没记过的路径 ⇒ 没被改过", () => {
    expect(会话改过("黄怡群/123.md")).toBe(false)
  })

  test("记过之后 ⇒ 被改过；别的路径不受影响", () => {
    记会话改过("黄怡群/123.md")

    expect(会话改过("黄怡群/123.md")).toBe(true)
    expect(会话改过("黄怡群/456.md")).toBe(false)
  })

  test("同一个路径记两次 ⇒ 仍然是「被改过」（幂等，不会记成两份）", () => {
    记会话改过("黄怡群/123.md")
    记会话改过("黄怡群/123.md")

    expect(会话改过("黄怡群/123.md")).toBe(true)
  })

  test("清掉之后 ⇒ 不再是「被改过」", () => {
    记会话改过("黄怡群/123.md")
    清会话改过("黄怡群/123.md")

    expect(会话改过("黄怡群/123.md")).toBe(false)
  })

  test("清一个没记过的路径 ⇒ 不抛错，也不碰别人", () => {
    记会话改过("甲.md")

    清会话改过("乙.md")

    expect(会话改过("甲.md")).toBe(true)
    expect(会话改过("乙.md")).toBe(false)
  })

  test("重载代按路径计：没触发过的路径恒 0，触发过的从 1 起往上加", () => {
    expect(当前重载代("黄怡群/123.md")).toBe(0)

    触发重载("黄怡群/123.md")
    expect(当前重载代("黄怡群/123.md")).toBe(1)
    // ⚠️ 按路径分是**要的**：分屏另一栏那份没被改过的文档不该跟着重挂（丢草稿）——
    //    这条是本模块唯一一条「分屏才咬得到」的判据，别顺手改成全局计数。
    expect(当前重载代("黄怡群/456.md")).toBe(0)

    触发重载("黄怡群/123.md")
    expect(当前重载代("黄怡群/123.md")).toBe(2)
    expect(当前重载代("黄怡群/456.md")).toBe(0)
  })

  test("清空 ⇒ 登记与每一份的重载代一起归零（换项目时喊它）", () => {
    记会话改过("黄怡群/123.md")
    触发重载("黄怡群/123.md")

    清空会话改过()

    expect(会话改过("黄怡群/123.md")).toBe(false)
    expect(当前重载代("黄怡群/123.md")).toBe(0)
  })
})

/**
 * 「内核报的绝对路径 → 中栏那一套项目相对路径」（2026-10-13）。
 *
 * 这是整个功能**最容易静默坏掉**的一环：两边口径不一致时**不报错、不变红**，只是圆点永远不出现
 * （`LEARNINGS #006-27` 那族）。所以它单独一组用例钉死——**这是本 feature 唯一一条能挡住
 * 「路径口径漂了」的用例**，别删。
 */
describe("内核事件路径 → 中栏相对路径（口径对齐）", () => {
  test("本项目的文件 ⇒ 切掉项目前缀，正斜杠相对路径", () => {
    expect(归一事件路径("/workspaces/u1/p2", "/workspaces/u1/p2", "/workspaces/u1/p2/黄怡群/123.md")).toBe(
      "黄怡群/123.md",
    )
  })

  test("不是本项目的文件 ⇒ undefined（另一个项目的同名文件不许点亮本项目那张 tab）", () => {
    expect(归一事件路径("/workspaces/u1/p9", "/workspaces/u1/p2", "/workspaces/u1/p9/黄怡群/123.md")).toBe(undefined)
  })

  test("⚠️ 目录前缀同头不算同目录（`p2` vs `p20`，只切「整段相等」的那一份）", () => {
    expect(归一事件路径("/workspaces/u1/p20", "/workspaces/u1/p2", "/workspaces/u1/p20/甲.md")).toBe(undefined)
  })

  test("还没选项目（当前项目目录 undefined）⇒ 一个都不登记", () => {
    expect(归一事件路径("/workspaces/u1/p2", undefined, "/workspaces/u1/p2/甲.md")).toBe(undefined)
  })

  test("win32：大小写与反斜杠都不算两种写法（同一个目录归一得空串）", () => {
    expect(归一事件路径("D:\\ws\\u1\\p2", "d:/ws/u1/p2", "D:\\ws\\u1\\p2\\甲.md")).toBe("甲.md")
  })

  /**
   * ⚠️ **上面那条挡不住这个缺陷**：`甲.md` 是**顶层文件**，相对路径里一个分隔符都没有 ⇒
   * 分隔符是不是反斜杠它看不出来。2026-10-14 真栈实测就是被这一点放过去的：内核报的是
   * `D:\…\p2\卷宗\纪要.md`，归一后回 **`卷宗\纪要.md`**（`normalize` 剥根那一步用 `slice`
   * 保留原生分隔符），而中栏 tab 的 path 是 **`卷宗/纪要.md`**（内核的文件清单给的就是正斜杠）
   * ⇒ 键对不上、圆点**永远不出现**，不报错、不变红（`LEARNINGS #006-23` 那一族）。
   *
   * 所以这一条**必须有一个带目录的文件**：判据是「分隔符折成正斜杠」，没目录段就量不到它。
   */
  test("win32：带目录的文件 ⇒ 相对路径里的分隔符折成正斜杠（与中栏 tab 的 path 同形）", () => {
    expect(归一事件路径("D:\\ws\\u1\\p2", "D:\\ws\\u1\\p2", "D:\\ws\\u1\\p2\\卷宗\\纪要.md")).toBe("卷宗/纪要.md")
  })
})
