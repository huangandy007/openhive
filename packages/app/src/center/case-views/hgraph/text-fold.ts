/**
 * 自由文字的字号与自动换行（012 · R-F11 / FR-024，修复轮 2026-11-16）。
 *
 * 画布是 SVG：`<text>` 的自动换行必须由我们算好、逐行给 `<tspan>`（浏览器不会折
 * `text`）。这里**只做估算**——按字符类别给宽度，不做真实字形测量（渲染前也没有
 * 可测量的布局）。口径：
 *
 * - 字号像素：小 11 / 中 16 / 大 22（画布 `font-size` 的唯一出处，`#002-06`）。
 * - 宽度估算：CJK/全角字符 = 字号像素；半角/ASCII = 字号像素 × 0.55。
 * - 折行：显式 `\n` 先分段；`宽度` 缺省或 ≤ 0 ⇒ 每段原样一行（不自动折）；否则按
 *   宽度贪心折（单行至少放 1 个字符，宽于整行的单字也不吐空行）。
 * - 空串 ⇒ `[""]`：仍渲染一个 `tspan`，元素不因空内容消失。
 */
import type { 文字 } from "./file"

/** 字号档 → 像素（唯一映射；画布不再另写一份 11/16/22）。 */
export function 字号像素(档: 文字["字号"]): number {
  if (档 === "小") return 11
  if (档 === "大") return 22
  return 16
}

/**
 * CJK / 全角范围（含 CJK 标点、假名、谚文、全角 ASCII、补充平面 CJK）。
 * 不在此范围内的一律按半角估算（含拉丁、数字、常见标点）。
 */
const 全角字符 =
  /[ᄀ-ᅟ⺀-〾ぁ-㏿㐀-䶿一-鿿ꀀ-꓏가-힣豈-﫿︰-﹏＀-｠￠-￦\u{20000}-\u{2fffd}\u{30000}-\u{3fffd}]/u

/** 单个字符的估算宽度（按码点判断，代理对整体算一个字符）。 */
function 字符宽(字: string, 像素: number): number {
  return 全角字符.test(字) ? 像素 : 像素 * 0.55
}

/** 一行文字的估算宽度；与 `折行行们` 同一套字宽口径（`#002-06`）。 */
export function 行宽(行文: string, 字号: 文字["字号"]): number {
  const 像素 = 字号像素(字号)
  let 宽 = 0
  for (const 字 of Array.from(行文)) 宽 += 字符宽(字, 像素)
  return 宽
}

/** 文字块在画布上的估算包围盒（内容坐标）。 */
export interface 文字盒 {
  readonly x: number
  readonly y: number
  readonly width: number
  readonly height: number
}

/** 行高固定为 1.35 字高（与 `<tspan dy>` 同一个数）。 */
const 行高倍 = 1.35
/** 基线到字顶约 0.9 字高；字底再留 0.3（≈1.2 总量）。 */
const 上沿倍 = 0.9
const 下沿倍 = 0.3

/**
 * 文字包围盒（2026-11-20 用户提出：文字要能选中高亮、能被框选、能一起拖）。
 *
 * 画布是 SVG，拿不到真实 `getBBox`（happy-dom 也没有布局），所以按 `折行行们` 的同一套
 * 估算算：宽 = 最长一行，高 = 行距 ×（行数 − 1）+ 1.2 字高。`x` 随对齐方式落到
 * 左 / 中 / 右；`y` 是首行基线往上 0.9 字高。只用于高亮与框选，不参与导出几何。
 */
export function 文字盒(行: 文字): 文字盒 {
  const 像素 = 字号像素(行.字号)
  const 行们 = 折行行们(行.内容, 行.宽度, 行.字号)
  const 宽 = Math.max(...行们.map((行文) => 行宽(行文, 行.字号)), 0)
  const 高 = (行们.length - 1) * 像素 * 行高倍 + 像素 * (上沿倍 + 下沿倍)
  const x = 行.对齐 === "左" ? 行.x : 行.对齐 === "右" ? 行.x - 宽 : 行.x - 宽 / 2
  return { x, y: 行.y - 像素 * 上沿倍, width: 宽, height: 高 }
}

/**
 * 把一段文字按 `宽度` 折成多行（估算）。`宽度` 是**内容的限宽**（像素），不是盒子宽。
 * 返回至少一项，调用方逐项渲染 `<tspan>`。
 */
export function 折行行们(内容: string, 宽度: number | undefined, 字号: 文字["字号"]): string[] {
  const 段们 = 内容.split("\n")
  if (宽度 === undefined || 宽度 <= 0) return 段们

  const 像素 = 字号像素(字号)
  const 行们: string[] = []
  for (const 段 of 段们) {
    let 现行 = ""
    let 现宽 = 0
    for (const 字 of Array.from(段)) {
      const 宽 = 字符宽(字, 像素)
      // `现行 !== ""` 保证单行至少 1 个字符：字宽超过整行也自己占一行。
      if (现行 !== "" && 现宽 + 宽 > 宽度) {
        行们.push(现行)
        现行 = 字
        现宽 = 宽
      } else {
        现行 += 字
        现宽 += 宽
      }
    }
    行们.push(现行)
  }
  return 行们
}
