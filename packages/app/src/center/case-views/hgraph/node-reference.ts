/**
 * 把关系图节点拖进右栏 AI 输入框时的**引用文本**（2026-11-20 用户提出）。
 *
 * 一行一个节点，形状由用户拍板：`节点ID：… ｜ 节点名称：…`。多选时按文档顺序换行排列。
 * 这是载荷形状的唯一出处（`#002-06`）：画布拼、测试断言、以后别的入口都从这里取，
 * 别在调用点手写模板串。
 */
import type { 节点 } from "./file"

/** 单个节点的引用行。名称为空（读放宽的旧文件）时写「（未命名）」，不留半截引用。 */
export function 节点引用行(点: 节点): string {
  const 名称 = 点.名称 === "" ? "（未命名）" : 点.名称
  return `节点ID：${点.id} ｜ 节点名称：${名称}`
}

/** 多个节点的引用文本：每行一个。空数组 ⇒ 空串（调用方据此不发）。 */
export function 节点引用文本(点们: readonly 节点[]): string {
  return 点们.map(节点引用行).join("\n")
}
