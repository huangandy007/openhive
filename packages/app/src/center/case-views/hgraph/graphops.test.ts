/**
 * 合并节点 / 复制粘贴的纯函数（012 · T016b，裁定 R79 / R80 / R97）。
 *
 * 口径：
 * - `合并计划(文档, 保留, 并入)` 只做「校验 + 组装一条 `合并节点` 操作」：并入去重、去掉
 *   保留者、过滤图上不存在的 id；合并集不足两颗 ⇒ 不发（`ok: false`）。
 * - 合并的逆操作由 `history.ts` 的 `逆操作` 生成（R79 整子图重建）；本文件断言它按合并集
 *   重建节点与夹边，且副本保留 `来源/出处/类型/坐标`——id 会变，不断言 id（R96）。
 * - `复制计划(文档, ids, 偏移)` 只产 `加节点/加边`（临时 id `c*`/`ce*`）：只取存在的节点；
 *   边只取**两端都在选区**的（含自环）；名称追加「副本」；坐标 `Math.round(x + 偏移)`。
 */
import { describe, expect, test } from "bun:test"
import type { 操作 } from "@/project/hgraph-api"
import type { 边, 图文件, 节点 } from "./file"
import { 逆操作 } from "./history"
import { 复制计划, 合并计划 } from "./graphops"

// ---------------------------------------------------------------------------
// 夹具
// ---------------------------------------------------------------------------

function 造节点(id: string, x = 100, y = 100, 补丁: Partial<节点> = {}): 节点 {
  return { id, 名称: id, 类型: "人", 来源: { kind: "手写" }, 时间: { 首: "", 末: "" }, x, y, ...补丁 }
}

function 造边(id: string, 从: string, 到: string, 补丁: Partial<边> = {}): 边 {
  return {
    id,
    从,
    到,
    标签: "联系",
    性质: "推断",
    方向: "有向",
    来源: { kind: "手写" },
    时间: { 首: "", 末: "" },
    ...补丁,
  }
}

function 一份图(补丁: Partial<图文件> = {}): 图文件 {
  return {
    格式: 1,
    标题: "测试图",
    创建于: "2026-11-16T10:00:00+08:00",
    更新于: "2026-11-16T10:00:00+08:00",
    设置: {
      线宽度量: "按类型默认",
      次数阈值: [1, 2, 5, 10, 50],
      金额阈值: [10000, 50000, 200000, 1000000],
      外环阈值: [1, 2, 4, 8],
    },
    节点: [造节点("n1"), 造节点("n2", 200, 100), 造节点("n3", 300, 100)],
    边: [造边("e1", "n1", "n2"), 造边("e2", "n2", "n3"), 造边("e3", "n3", "n1")],
    文字: [],
    ...补丁,
  }
}

const 类型序列 = (操作们: readonly 操作[]) => 操作们.map((条) => 条.操作)

// ---------------------------------------------------------------------------
// 合并计划（验收 #11 / #12）
// ---------------------------------------------------------------------------

describe("合并计划", () => {
  test("#11 组装一条 合并节点：并入去重、不含保留者；逆操作 = 删保留者 + 加节点(合并集大小) + 加边(夹边数)", () => {
    const 文档 = 一份图()
    // 选中里可能带保留者（UI 把整份选中传进来）与重复 id。
    const 计划 = 合并计划(文档, "n1", ["n1", "n2", "n2", "n3"])
    expect(计划.ok).toBe(true)
    if (!计划.ok) return

    expect(计划.操作).toEqual({ 操作: "合并节点", 保留: "n1", 并入: ["n2", "n3"] })
    expect(计划.并入).toEqual(["n2", "n3"])

    const 逆 = 逆操作(文档, [计划.操作])
    expect(类型序列(逆.逆操作)).toEqual(["删对象", "加节点", "加边"])
    const 删 = 逆.逆操作[0]!
    if (删.操作 !== "删对象") throw new Error("期望删对象")
    expect(删.目标).toEqual([{ 类别: "节点", id: "n1" }])
    const 加节点 = 逆.逆操作[1]!
    if (加节点.操作 !== "加节点") throw new Error("期望加节点")
    expect(加节点.节点.map((行) => 行.名称)).toEqual(["n1", "n2", "n3"])
    const 加边 = 逆.逆操作[2]!
    if (加边.操作 !== "加边") throw new Error("期望加边")
    // 任一夹点属于合并集的边：e1(n1-n2)、e2(n2-n3)、e3(n3-n1)。
    expect(加边.边).toHaveLength(3)
  })

  test("#12 逆操作节点副本保留 名称/类型/坐标/来源/出处（id 会变，不比较 id）", () => {
    const 文档 = 一份图({
      节点: [
        造节点("n1", 100, 100, {
          名称: "张三",
          类型: "人",
          来源: { kind: "实体", 实体: "e1", 值: "张三" },
          出处: ["甲"],
        }),
        造节点("n2", 240, 160, {
          名称: "李四",
          类型: "账户",
          来源: { kind: "实体", 实体: "e2", 值: "李四", 并入: ["e0"] },
          出处: ["乙", "丙"],
        }),
      ],
      边: [造边("e1", "n1", "n2")],
    })
    const 计划 = 合并计划(文档, "n1", ["n1", "n2"])
    expect(计划.ok).toBe(true)
    if (!计划.ok) return

    const 逆 = 逆操作(文档, [计划.操作])
    const 加节点 = 逆.逆操作[1]!
    if (加节点.操作 !== "加节点") throw new Error("期望加节点")
    const 剥离 = (行: Record<string, unknown>) => ({
      名称: 行.名称,
      类型: 行.类型,
      来源: 行.来源,
      出处: 行.出处,
      x: 行.x,
      y: 行.y,
    })
    expect(加节点.节点.map(剥离)).toEqual(文档.节点.map((点) => 剥离(点 as unknown as Record<string, unknown>)))
  })

  test("并入为空 / 合并集不足两颗 / 保留者不在图上 ⇒ 不发（ok:false）", () => {
    const 文档 = 一份图()
    expect(合并计划(文档, "n1", ["n1"]).ok).toBe(false)
    expect(合并计划(文档, "n1", []).ok).toBe(false)
    expect(合并计划(文档, "n9", ["n1", "n2"]).ok).toBe(false)

    // 不存在的并入 id 被过滤；过滤后不足两颗也不发。
    expect(合并计划(文档, "n1", ["n9"]).ok).toBe(false)
    const 计划 = 合并计划(文档, "n1", ["n2", "n9"])
    expect(计划.ok).toBe(true)
    if (计划.ok) expect(计划.并入).toEqual(["n2"])
  })
})

// ---------------------------------------------------------------------------
// 复制计划（验收 #13 / #14 / #15）
// ---------------------------------------------------------------------------

describe("复制计划", () => {
  test("#13 只带两端都在选区的边（含自环）；节点名称加「副本」；不存在的 id 跳过", () => {
    const 文档 = 一份图({
      节点: [造节点("n1"), 造节点("n2", 200, 100), 造节点("n3", 300, 100)],
      边: [造边("e1", "n1", "n2"), 造边("e2", "n2", "n3"), 造边("e3", "n1", "n1")],
    })
    const 计划 = 复制计划(文档, ["n1", "n2", "n9"], 24)

    expect(类型序列(计划)).toEqual(["加节点", "加边"])
    const 加节点 = 计划[0]!
    if (加节点.操作 !== "加节点") throw new Error("期望加节点")
    expect(加节点.节点.map((行) => 行.名称)).toEqual(["n1副本", "n2副本"])
    // 节点临时 id：`临时c*` 形状（与正式 id / 其它临时前缀区分）。
    expect(加节点.节点.map((行) => String(行.id))).toEqual([
      expect.stringMatching(/^临时c\d+$/),
      expect.stringMatching(/^临时c\d+$/),
    ])

    const 加边 = 计划[1]!
    if (加边.操作 !== "加边") throw new Error("期望加边")
    // e2 只有一端在选区 ⇒ 不复制；e1、自环 e3 复制。
    expect(加边.边).toHaveLength(2)
    expect(加边.边.map((行) => String(行.id))).toEqual([
      expect.stringMatching(/^临时ce\d+$/),
      expect.stringMatching(/^临时ce\d+$/),
    ])
    const 临时节点 = new Set(加节点.节点.map((行) => String(行.id)))
    for (const 条 of 加边.边) {
      expect(临时节点.has(String(条.从))).toBe(true)
      expect(临时节点.has(String(条.到))).toBe(true)
    }
  })

  test("#14 偏移 24 且取整：x/y 都 +24；全字段（来源/出处/时间）照旧", () => {
    const 文档 = 一份图({
      节点: [
        造节点("n1", 100.4, 99.6, {
          来源: { kind: "实体", 实体: "e1", 值: "张三" },
          出处: ["甲"],
          时间: { 首: "2026-01-01", 末: "2026-02-02" },
        }),
      ],
      边: [],
    })
    const 计划 = 复制计划(文档, ["n1"], 24)
    const 加节点 = 计划[0]!
    if (加节点.操作 !== "加节点") throw new Error("期望加节点")
    const 行 = 加节点.节点[0]!
    expect(行.x).toBe(124)
    expect(行.y).toBe(124)
    expect(行.来源).toEqual({ kind: "实体", 实体: "e1", 值: "张三" })
    expect(行.出处).toEqual(["甲"])
    expect(行.时间).toEqual({ 首: "2026-01-01", 末: "2026-02-02" })
    // 副本不带正式 id。
    expect(行.id).not.toBe("n1")
  })

  test("偏移 0 原地；只取节点（文字/边 id 不会被当成节点）；空选集 ⇒ 空计划", () => {
    const 文档 = 一份图({ 边: [] })
    const 计划 = 复制计划(文档, ["n1"], 0)
    const 加节点 = 计划[0]!
    if (加节点.操作 !== "加节点") throw new Error("期望加节点")
    expect([加节点.节点[0]!.x, 加节点.节点[0]!.y]).toEqual([100, 100])

    expect(复制计划(文档, [], 24)).toEqual([])
    expect(复制计划(文档, ["t1", "e1"], 24)).toEqual([])
  })

  test("边快照过滤（剪贴板）：第 4 个参数只复制点名过的边", () => {
    const 文档 = 一份图({
      边: [造边("e1", "n1", "n2"), 造边("e3", "n1", "n1")],
    })
    const 计划 = 复制计划(文档, ["n1", "n2"], 24, ["e1"])
     expect(类型序列(计划)).toEqual(["加节点", "加边"])
    const 加边 = 计划[1]!
    if (加边.操作 !== "加边") throw new Error("期望加边")
    expect(加边.边).toHaveLength(1)
    // 源边已不在文档 ⇒ 跳过（不报错）。
    const 空 = 复制计划(文档, ["n1", "n2"], 24, ["e9"])
    expect(类型序列(空)).toEqual(["加节点"])
  })
})
