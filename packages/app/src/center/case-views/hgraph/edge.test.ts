// T012 · 边线型（实线 / 点线 / 虚线，只此一处判定）
// ---------------------------------------------------------------------------

describe("T012 · 边线型", () => {
  const 事件点 = (id: string): 节点 => ({
    id,
    名称: `${id}事件`,
    类型: "转账",
    来源: { kind: "手写" },
    属性: [{ 键: "时间精度", 值: "分" }],
    时间: { 首: "", 末: "" },
    x: 0,
    y: 0,
  })
  const 普通点 = (id: string): 节点 => ({
    id,
    名称: id,
    类型: "人",
    来源: { kind: "手写" },
    时间: { 首: "", 末: "" },
    x: 0,
    y: 0,
  })

  test("角色边（依据与角色边依据逐字相等）+ 起点事件 ⇒ 实线", () => {
    const 起 = 事件点("ev1")
    const 条 = 角色边(起, "n2", "付款方")
    expect(边线型(条, 起, 普通点("n2"))).toBe("实线")
  })

  test("两事件之间标签 ∈ {先, 同时, 同一事件} ⇒ 点线", () => {
    const 甲 = 事件点("e1")
    const 乙 = 事件点("e2")
    for (const 标签 of ["先", "同时", "同一事件"]) {
      const 条 = 手画边("e1", "e2", { 依据: "时序", 可信度: "中", 标签 })
      expect(边线型(条, 甲, 乙)).toBe("点线")
    }
  })

  test("普通手画推断边 ⇒ 虚线", () => {
    const 条 = 手画边("a", "b", { 依据: "联系", 可信度: "中", 标签: "联系" })
    expect(边线型(条, 普通点("a"), 普通点("b"))).toBe("虚线")
  })

  test("事实边 ⇒ 实线", () => {
    const 条: 边 = {
      id: "e1",
      从: "a",
      到: "b",
      标签: "转账",
      性质: "事实",
      方向: "有向",
      来源: { kind: "手写" },
      时间: { 首: "", 末: "" },
    }
    expect(边线型(条, 普通点("a"), 普通点("b"))).toBe("实线")
  })
})
