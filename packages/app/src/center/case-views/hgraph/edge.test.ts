/**
 * 手画边纯构造器（012 · K1 / R-F1，修复轮 2026-11-16）。
 *
 * 口径：手画边**固定** `性质:"推断"`、`来源 = {kind:"手写", 依据}`（FR-006 / FR-017：
 * 任何入口拒绝无依据推断；设计 §5.7.2.1：手工对象无出处）。构造器只产数据，不发写、不碰 UI。
 */
import { describe, expect, test } from "bun:test"
import { 可连线, 边线型, 手画边, 角色边, 角色边依据 } from "./edge"
import type { 边, 节点 } from "./file"

describe("手画边", () => {
  test("每个字段逐字钉死：推断 / 有向 / 手写来源 / 空时间 / 空标签", () => {
    const 条 = 手画边("n1", "n2", { 依据: "两人同日同酒店入住", 可信度: "中" })

    expect(条).toEqual({
      id: expect.stringMatching(/^临时e\d+$/),
      从: "n1",
      到: "n2",
      标签: "",
      性质: "推断",
      方向: "有向",
      来源: { kind: "手写", 依据: "两人同日同酒店入住" },
      可信度: "中",
      时间: { 首: "", 末: "" },
    })
  })

  test("显式 id 原样使用；可选 `标签` / `方向` 照传", () => {
    const 条 = 手画边("n1", "n2", { 依据: "转账", 可信度: "高", 标签: "资金", 方向: "无向" }, "临时e42")

    expect(条.id).toBe("临时e42")
    expect(条.标签).toBe("资金")
    expect(条.方向).toBe("无向")
    expect(条.可信度).toBe("高")
  })

  test("`依据` 原文保留：不去空格、不 trim（与后端 `非空串` 只判有没有内容同口径）", () => {
    const 条 = 手画边("n1", "n2", { 依据: "  两人 同日  ", 可信度: "低" })

    expect(条.来源).toEqual({ kind: "手写", 依据: "  两人 同日  " })
    expect(条.可信度).toBe("低")
  })

  test("两次调用得到不同临时 id（共用 `temp-id` 计数器）", () => {
    const 甲 = 手画边("n1", "n2", { 依据: "甲", 可信度: "中" })
    const 乙 = 手画边("n1", "n2", { 依据: "乙", 可信度: "中" })

    expect(甲.id).not.toBe(乙.id)
  })
})

describe("可连线", () => {
  test("只有空白 ⇒ false；有内容 ⇒ true（UI 用它禁用确认）", () => {
    expect(可连线("")).toBe(false)
    expect(可连线("   ")).toBe(false)
    expect(可连线("\n\t")).toBe(false)
    expect(可连线("甲")).toBe(true)
    expect(可连线("  甲  ")).toBe(true)
  })
})

// ---------------------------------------------------------------------------
// T012 · 事件 → 参与方角色边（data-model §4 / FR-027）
// ---------------------------------------------------------------------------

const 造事件 = (补丁: Partial<节点> = {}): 节点 => ({
  id: "ev1",
  名称: "李四向王五转账",
  类型: "转账",
  来源: { kind: "手写" },
  时间: { 首: "2026-11-17 09:30", 末: "2026-11-17 09:30" },
  x: 380,
  y: 340,
  ...补丁,
})

describe("T012 · 角色边依据话术", () => {
  test("手写事件：`手写事件「<摘要>」的<角色>` 逐字匹配（摘要取节点名称）", () => {
    expect(角色边依据(造事件(), "付款方")).toBe("手写事件「李四向王五转账」的付款方")
    expect(角色边依据(造事件({ 名称: "某宾馆同住" }), "同住人")).toBe("手写事件「某宾馆同住」的同住人")
  })

  test("库事件：`库事件 <event_id> 的<角色>` 逐字匹配（id 取 `来源.实体`）", () => {
    const 库 = 造事件({ 来源: { kind: "事件", 实体: "ev-42", 库类型: "转账", 可信: "已核实" } })

    expect(角色边依据(库, "收款方")).toBe("库事件 ev-42 的收款方")
  })

  test("角色边构造：标签=角色、性质推断、有向、来源推断 + 固定依据、可信度默认中", () => {
    const 条 = 角色边(造事件(), "n2", "付款方")

    expect(条).toEqual({
      id: expect.stringMatching(/^临时e\d+$/),
      从: "ev1",
      到: "n2",
      标签: "付款方",
      性质: "推断",
      方向: "有向",
      来源: { kind: "推断", 依据: "手写事件「李四向王五转账」的付款方" },
      可信度: "中",
      时间: { 首: "", 末: "" },
    })
  })

  test("库事件的角色边：依据换成 `库事件 <id> 的<角色>`，可信度可显式给", () => {
    const 库 = 造事件({ 来源: { kind: "事件", 实体: "ev-42" } })
    const 条 = 角色边(库, "n3", "收款方", "高")

    expect(条.来源).toEqual({ kind: "推断", 依据: "库事件 ev-42 的收款方" })
    expect(条.可信度).toBe("高")
    expect(条.标签).toBe("收款方")
  })
})

