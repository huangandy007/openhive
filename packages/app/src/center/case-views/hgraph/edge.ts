/**
 * 手画边的纯构造器（012 · K1 / R-F1，修复轮 2026-11-16）。
 *
 * ## 为什么单独一个模块
 *
 * 「手画一条边」要落成什么样是**数据规则**，不是 UI 细节：性质固定推断、来源固定
 * `{kind:"手写", 依据}`。构造器只产 `边` 对象，写盘、压栈、提示都在 `editor.tsx`
 * ——UI 与跨层契约测试（`packages/opencode`）共用同一份规则，不各写一遍（`#002-06`）。
 *
 * ## 固定值从哪来
 *
 * - `性质: "推断"`：本阶段库不提供行级 locator，手工连线不能标事实（R-F1；FR-006/FR-017
 *   要求任何入口拒绝无依据推断）。
 * - `来源: {kind:"手写", 依据}`：手工对象没有出处，出处只能来自从库加入 / AI（设计 §5.7.2.1）。
 * - `可信度` 由连线浮层必填（默认「中」）；本构造器只照传，不替 UI 定默认。
 */
import type { 节点, 边 } from "./file"
import { 临时id } from "./temp-id"

export interface 连线输入 {
  readonly 依据: string
  readonly 可信度: "高" | "中" | "低"
  readonly 标签?: string
  readonly 方向?: "有向" | "无向"
}

/** 手画边：性质固定推断；来源固定手写 + 依据（FR-006/FR-017，来源见 R-F1）。 */
export function 手画边(从: string, 到: string, 输入: 连线输入, id?: string): 边 {
  return {
    id: id ?? 临时id("e"),
    从,
    到,
    标签: 输入.标签 ?? "",
    性质: "推断",
    方向: 输入.方向 ?? "有向",
    来源: { kind: "手写", 依据: 输入.依据 },
    可信度: 输入.可信度,
    时间: { 首: "", 末: "" },
  }
}

/** UI 用它禁用「确认」：依据只有空白等于没写（与后端 `非空串` 同口径）。 */
export function 可连线(依据: string): boolean {
  return 依据.trim() !== ""
}

/**
 * 角色边依据话术（data-model §4 / FR-027）：固定两种前缀，不写条款 / 页码 / 时间。
 *
 * - 手写事件 ⇒ `手写事件「<摘要>」的<角色>`（摘要取节点 `名称`）
 * - 库事件 ⇒ `库事件 <event_id> 的<角色>`（id 取 `来源.实体`）
 *
 * 话术只在 `角色边` 与检查器展示之间共用这一份；别在 UI 里另拼字符串（`#002-06`）。
 */
export function 角色边依据(事件: 节点, 角色: string): string {
  if (事件.来源?.kind === "事件") return `库事件 ${事件.来源.实体 ?? ""} 的${角色}`
  return `手写事件「${事件.名称}」的${角色}`
}

/**
 * 事件 → 参与方角色边（data-model §4）：标签 = 角色、性质固定推断、方向有向、
 * 来源固定推断 + 固定依据、可信度默认「中」。实线 1px + 箭头由画布按边属性渲染。
 *
 * 与 `手画边` 的区别只有来源类别：角色边是**推断出来**的参与关系（有依据），
 * 不是用户在画布上随手画的一条手写边。
 */
export function 角色边(
  事件: 节点,
  参与方: string,
  角色: string,
  可信度: "高" | "中" | "低" = "中",
  id?: string,
): 边 {
  return {
    id: id ?? 临时id("e"),
    从: 事件.id,
    到: 参与方,
    标签: 角色,
    性质: "推断",
    方向: "有向",
    来源: { kind: "推断", 依据: 角色边依据(事件, 角色) },
    可信度,
    时间: { 首: "", 末: "" },
  }
}
