/**
 * FR-003：手动新增节点的默认名递增（`新节点 1`、`新节点 2`…），不得固定同名。
 *
 * 判据取**最大值 + 1**（不是「节点数 + 1」）：删掉中间一个之后再加，不能与现存名字撞车。
 */
import { describe, expect, test } from "bun:test"
import type { 图文件, 节点, 设置 } from "./file"
import { 下一个默认名 } from "./default-name"

const 设置: 设置 = {
  线宽度量: "按类型默认",
  次数阈值: [1, 2, 5, 10, 50],
  金额阈值: [10000, 50000, 200000, 1000000],
  外环阈值: [1, 2, 4, 8],
}

function 造节点(id: string, 名称: string): 节点 {
  return { id, 名称, 类型: "未分类", 来源: { kind: "手写" }, 时间: { 首: "", 末: "" }, x: 0, y: 0 }
}

function 造图(名称们: string[]): 图文件 {
  return {
    格式: 1,
    标题: "图",
    创建于: "",
    更新于: "",
    设置: { ...设置 },
    节点: 名称们.map((名称, 序) => 造节点(`n${序 + 1}`, 名称)),
    边: [],
    文字: [],
  }
}

describe("下一个默认名（FR-003）", () => {
  test("空图 ⇒ 新节点 1", () => {
    expect(下一个默认名(造图([]))).toBe("新节点 1")
  })

  test("已有 1、2 ⇒ 新节点 3（连加两次的实际结果）", () => {
    expect(下一个默认名(造图(["新节点 1", "新节点 2"]))).toBe("新节点 3")
  })

  test("删掉 1 后只剩 2 ⇒ 新节点 3（取最大 +1，不是补空位）", () => {
    expect(下一个默认名(造图(["新节点 2"]))).toBe("新节点 3")
  })

  test("不匹配的名字不参与编号（张三 / 新节点甲 / 新节点 3 个都忽略）", () => {
    expect(下一个默认名(造图(["张三", "新节点甲", "我的新节点 9"]))).toBe("新节点 1")
  })

  test("裸「新节点」按 1 计；多位数取数值最大", () => {
    expect(下一个默认名(造图(["新节点"]))).toBe("新节点 2")
    expect(下一个默认名(造图(["新节点 9", "新节点 10"]))).toBe("新节点 11")
  })
})
