/**
 * 绑定到库实体的一次性补丁（FR-027 / R-F9）。
 *
 * 检查器对手写/推断节点提供「绑定到库实体」：选中一个库实体后，用**一条 `改字段`**
 * 把来源换成实体快照、属性/出处/时间换成库里的只读快照。
 *
 * ## 只换快照四件套
 *
 * 名称 / 类型 / 细类 / 可信度**不写**：那是用户在图里写的（绑定不该按库里的名字改名，
 * 也不该把推断/手写节点的可信度悄悄改档）。状态随 `来源.kind` 变，不需要另写 `可信度`。
 *
 * ## R59：出处恒空
 *
 * 流水线引用 locator 只有切片 `{start,end}`，拼不出「材料#工作表#行号」——宁给空数组，
 * 不伪造行级出处。检查器对「已绑库 + 空」显示「未取到出处」。
 */
import type { 实体档案, 档案关系 } from "../../case-detail-api"
import type { 来源, 时间 } from "./file"
import { 日期文本 } from "../format"

/**
 * `实体档案` → `来源` 实体快照（data-model §5.1 逐字）。
 *
 * 「从库加入」建整颗节点与「绑定到库实体」发一次性补丁都从这里取——快照形状只有一处
 * 实现（`#002-06`），别在两处各拼一份。
 */
export function 来源快照(档案: 实体档案): 来源 {
  return {
    kind: "实体",
    实体: 档案.id,
    值: 档案.canonical_value,
    库类型: 档案.type,
    可信: 档案.trust_state,
  }
}

/**
 * 首末时间 = 全部关系里 `首` 的 min / `末` 的 max（不是首条）。
 * 没有任何可用值 ⇒ `{首:"",末:""}`（不编时刻）。
 */
export function 时间跨度(关系们: readonly 档案关系[]): 时间 {
  const 首们 = 关系们.flatMap((行) => (行.首 === null ? [] : [行.首]))
  const 末们 = 关系们.flatMap((行) => (行.末 === null ? [] : [行.末]))
  return {
    首: 首们.length === 0 ? "" : 日期文本(Math.min(...首们)),
    末: 末们.length === 0 ? "" : 日期文本(Math.max(...末们)),
  }
}

/**
 * `实体档案` → `改字段` 补丁（来源/属性/出处/时间，见文件头）。
 *
 * 属性口径与「从库加入」的 `属性们`（`entity-picker.tsx`）一致：`null`/`undefined` 都是
 * 「库中无值」⇒ 跳过，不写 `"null"` 这种把空值当文字的做法（`#002-06`：同一前提一处口径）。
 */
export function 绑定补丁(档案: 实体档案): Record<string, unknown> {
  return {
    来源: 来源快照(档案),
    属性: Object.entries(档案.attrs).flatMap(([键, 值]) =>
      值 === undefined || 值 === null ? [] : [{ 键, 值: typeof 值 === "string" ? 值 : JSON.stringify(值) }],
    ),
    出处: [],
    时间: 时间跨度(档案.关系),
  }
}
