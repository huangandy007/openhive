describe("逆操作 · 删对象 ⇒ 带完整副本还原", () => {
  test("#2 删节点（带 2 条边）⇒ 逆操作含 1 条加节点 + 1 条加边（2 条）；副本 3 份且不与文档共享引用", () => {
    const 文档 = 一份图({
      节点: [造节点("n1"), 造节点("n2", 200, 100), 造节点("n3", 300, 100)],
      边: [造边("e1", "n1", "n2"), 造边("e2", "n2", "n3")],
    })
    const 出 = 逆操作(文档, [{ 操作: "删对象", 目标: [{ 类别: "节点", id: "n2" }] }])

    expect(类型序列(出.逆操作)).toEqual(["加节点", "加边"])
    const 加节点 = 出.逆操作[0]
    if (加节点.操作 !== "加节点") throw new Error("期望加节点")
    expect(加节点.节点).toHaveLength(1)
    expect(加节点.节点[0]).toEqual(文档.节点[1]! as unknown as Record<string, unknown>)

    const 加边 = 出.逆操作[1]
    if (加边.操作 !== "加边") throw new Error("期望加边")
    expect(加边.边.map((条) => [条.id, 条.从, 条.到])).toEqual([
      ["e1", "n1", "n2"],
      ["e2", "n2", "n3"],
    ])

    // 副本：被删节点 + 两条被级联删掉的边。
    expect(出.副本?.map((份) => [份.类别, (份.对象 as { id: string }).id])).toEqual([
      ["节点", "n2"],
      ["边", "e1"],
      ["边", "e2"],
    ])
    // 深拷贝：后续改文档不会污染副本（#005-48）。
    expect(加节点.节点[0]).not.toBe(文档.节点[1]!)
  })

  test("删边 / 删文字 ⇒ 各自原样带回；同一对象被节点级联与显式点名时只加一次", () => {
    const 文档 = 一份图()
    const 出 = 逆操作(文档, [
      { 操作: "删对象", 目标: [{ 类别: "节点", id: "n1" }, { 类别: "边", id: "e1" }] },
      { 操作: "删对象", 目标: [{ 类别: "文字", id: "t1" }] },
    ])
    // 新增类还原按依赖顺序统一放在最前：加节点 → 加边 → 加文字。加边只有一条 e1。
    expect(类型序列(出.逆操作)).toEqual(["加节点", "加边", "加文字"])
    const 加边 = 出.逆操作[1]
    if (加边.操作 !== "加边") throw new Error("期望加边")
    expect(加边.边.map((条) => 条.id)).toEqual(["e1"])
  })
})

