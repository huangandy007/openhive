function 造节点(id: string, x = 100, y = 100, 补丁: Partial<节点> = {}): 节点 {
  return { id, 名称: id, 类型: "人", 来源: { kind: "手写" }, 时间: { 首: "", 末: "" }, x, y, ...补丁 }
}

function 造边(id: string, 从: string, 到: string, 补丁: Partial<边> = {}): 边 {
  return {
    id,
    从,
    到,
    标签: "联系",
    性质: "推断",
    方向: "有向",
    来源: { kind: "手写" },
    时间: { 首: "", 末: "" },
    ...补丁,
  }
}

function 造文字(id: string, 内容: string, x = 50, y = 50): 文字 {
  return { id, 内容, x, y, 字号: "中" }
}

function 一份图(补丁: Partial<图文件> = {}): 图文件 {
  return {
    格式: 1,
    标题: "测试图",
    创建于: "2026-11-16T10:00:00+08:00",
    更新于: "2026-11-16T10:00:00+08:00",
    设置: {
      线宽度量: "按类型默认",
      次数阈值: [1, 2, 5, 10, 50],
      金额阈值: [10000, 50000, 200000, 1000000],
      外环阈值: [1, 2, 4, 8],
    },
    节点: [造节点("n1"), 造节点("n2", 200, 100)],
    边: [造边("e1", "n1", "n2")],
    文字: [造文字("t1", "备注")],
    ...补丁,
  }
}

/** 操作数组的「类型序列」，便于断言逆序/依赖顺序。 */
const 类型序列 = (操作们: readonly 操作[]) => 操作们.map((条) => 条.操作)

