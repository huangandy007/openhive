describe("逆操作 · 合并节点（R79，整子图重建）", () => {
  test("保留者 + 被并入者 + 全部夹边：先删保留者，再加节点副本（临时 id），再加边（两端改指临时 id）", () => {
    const 文档 = 一份图({
      节点: [造节点("n1"), 造节点("n2", 200, 100), 造节点("n3", 300, 100)],
      边: [造边("e1", "n1", "n2"), 造边("e2", "n2", "n3"), 造边("e3", "n3", "n1")],
      文字: [],
    })
    const 出 = 逆操作(文档, [{ 操作: "合并节点", 保留: "n1", 并入: ["n2"] }])

    expect(类型序列(出.逆操作)).toEqual(["删对象", "加节点", "加边"])
    const 删 = 出.逆操作[0]
    if (删.操作 !== "删对象") throw new Error("期望删对象")
    expect(删.目标).toEqual([{ 类别: "节点", id: "n1" }])

    const 加节点 = 出.逆操作[1]
    if (加节点.操作 !== "加节点") throw new Error("期望加节点")
    expect(加节点.节点.map((行) => 行.名称)).toEqual(["n1", "n2"])
    // 不带正式 id：同一批里删过又加同一 id 会被服务端 fail-closed；用临时 id 供边引用。
    const 临时 = 加节点.节点.map((行) => 行.id).filter((id): id is string => typeof id === "string")
    expect(临时).toHaveLength(2)
    expect(临时.every((id) => id.startsWith("临时"))).toBe(true)

    const 加边 = 出.逆操作[2]
    if (加边.操作 !== "加边") throw new Error("期望加边")
    // 旧文档里任一夹点属于合并集的边全部重建：e1、e2、e3。
    expect(加边.边.map((条) => 条.id).length).toBe(3)
    const 临时节点 = new Set([...加节点.节点.map((行) => 行.id)])
    for (const 条 of 加边.边) {
      // 合并集内的端点改指临时 id；集外存活端点（如 n3）保持原 id。
      expect(临时节点.has(条.从 as string) || 临时节点.has(条.到 as string)).toBe(true)
    }
    expect(出.副本?.filter((份) => 份.类别 === "节点")).toHaveLength(2)
  })

  /**
   * I1（修复轮 2026-11-16）：合并撤销按**解析后的文档**重建夹边；边 `可信度` 若在解析投影
   * 时被丢掉，撤销重建的推断边就没有可信度。夹具先序列化再解析，走真实管道。
   */
  test("合并撤销重建的边保留 `可信度`（I1）", () => {
    const 解析 = 解析图(
      JSON.stringify({
        ...一份图({ 节点: [造节点("n1"), 造节点("n2", 200, 100)], 边: [], 文字: [] }),
        边: [
          {
            id: "e1",
            从: "n1",
            到: "n2",
            标签: "联系",
            性质: "推断",
            方向: "有向",
            来源: { kind: "手写", 依据: "甲" },
            可信度: "中",
            时间: { 首: "", 末: "" },
          },
        ],
      }),
    )
    if (!解析.ok) throw new Error(`不该失败：${解析.说明}`)

    const 出 = 逆操作(解析.文档, [{ 操作: "合并节点", 保留: "n1", 并入: ["n2"] }])
    const 加边 = 出.逆操作.find((条) => 条.操作 === "加边")
    if (加边 === undefined || 加边.操作 !== "加边") throw new Error("期望加边")
    expect(加边.边).toHaveLength(1)
    expect((加边.边[0] as Record<string, unknown>).可信度).toBe("中")
  })
})

