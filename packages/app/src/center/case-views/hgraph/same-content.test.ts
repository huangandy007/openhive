/**
 * `same-content.ts`：FR-007 的规范化比较（忽略服务端重分配的 id、忽略 `更新于`）。
 *
 * 每条用例都先钉「同一份内容在 id 全换后仍相等」，再钉「任一字段真变了就不相等」——
 * 只测相等会漏掉「恒返回 true」的哑实现。
 */
import { describe, expect, test } from "bun:test"
import type { 边, 图文件, 节点, 设置, 文字 } from "./file"
import { 同内容 } from "./same-content"

const 设置: 设置 = {
  线宽度量: "按类型默认",
  次数阈值: [1, 2, 5, 10, 50],
  金额阈值: [10000, 50000, 200000, 1000000],
  外环阈值: [1, 2, 4, 8],
}

function 造节点(id: string, 补丁: Partial<节点> = {}): 节点 {
  return { id, 名称: `名-${id}`, 类型: "人", 来源: { kind: "手写" }, 时间: { 首: "", 末: "" }, x: 10, y: 20, ...补丁 }
}

function 造边(id: string, 从: string, 到: string, 补丁: Partial<边> = {}): 边 {
  return { id, 从, 到, 标签: "认识", 性质: "事实", 方向: "无向", 来源: { kind: "手写" }, 时间: { 首: "", 末: "" }, ...补丁 }
}

function 造文字(id: string): 文字 {
  return { id, 内容: "备注", x: 1, y: 2, 字号: "中" }
}

function 造图(): 图文件 {
  return {
    格式: 1,
    标题: "图",
    创建于: "2026-11-16T10:00:00+08:00",
    更新于: "2026-11-16T10:00:00+08:00",
    设置: { ...设置 },
    节点: [
      造节点("n1", { x: 180, 属性: [{ 键: "金额", 值: "100 元" }], 样式: { 颜色: "红" } }),
      造节点("n2", { 类型: "号码" }),
    ],
    边: [造边("e1", "n1", "n2", { 证据: [{ 关系: "通话", 出处: "m#t#1" }], 时间: { 首: "a", 末: "b" } })],
    文字: [造文字("t1")],
  }
}

/** 把一份图的 id 全部换掉（模拟服务端重分配），边的端点跟着映射。 */
function 换id(图: 图文件): 图文件 {
  const 节点映射 = new Map(图.节点.map((点, 序) => [点.id, `正式n${序 + 1}`]))
  const 文字映射 = new Map(图.文字.map((行, 序) => [行.id, `正式t${序 + 1}`]))
  return {
    ...图,
    节点: 图.节点.map((点) => ({ ...点, id: 节点映射.get(点.id)! })),
    边: 图.边.map((条) => ({
      ...条,
      id: `正式e1`,
      从: 节点映射.get(条.从)!,
      到: 节点映射.get(条.到)!,
    })),
    文字: 图.文字.map((行) => ({ ...行, id: 文字映射.get(行.id)! })),
  }
}

describe("同内容（FR-007 规范化比较）", () => {
  test("同一内容、节点/边/文字 id 全换 ⇒ 仍相等（位置对齐 + 边端点换位置序号）", () => {
    const 甲 = 造图()
    const 乙 = 换id(甲)
    乙.更新于 = "2026-11-17T09:00:00+08:00"
    expect(同内容(甲, 乙)).toBe(true)
    expect(同内容(乙, 甲)).toBe(true)
  })

  test("任一业务字段不同 ⇒ 不相等（逐个字段各测一次）", () => {
    const 基 = 造图()
    const 改设置 = { ...基, 设置: { ...基.设置, 次数阈值: [9] } }
    expect(同内容(基, 改设置)).toBe(false)

    const 改节点 = structuredClone(基)
    改节点.节点[0]!.属性 = [{ 键: "金额", 值: "200 元" }]
    expect(同内容(基, 改节点)).toBe(false)

    const 改样式 = structuredClone(基)
    改样式.节点[0]!.样式 = { 颜色: "蓝" }
    expect(同内容(基, 改样式)).toBe(false)

    const 改来源 = structuredClone(基)
    改来源.节点[1]!.来源 = { kind: "实体", 实体: "x1" }
    expect(同内容(基, 改来源)).toBe(false)

    const 改时间 = structuredClone(基)
    改时间.边[0]!.时间 = { 首: "a", 末: "c" }
    expect(同内容(基, 改时间)).toBe(false)

    const 改文字 = structuredClone(基)
    改文字.文字[0]!.内容 = "别的"
    expect(同内容(基, 改文字)).toBe(false)

    const 改坐标 = structuredClone(基)
    改坐标.节点[0]!.x = 181
    expect(同内容(基, 改坐标)).toBe(false)
  })

  test("节点/边/文字条数不同 ⇒ 不相等", () => {
    const 基 = 造图()
    const 多节点 = { ...基, 节点: [...基.节点, 造节点("n9")] }
    expect(同内容(基, 多节点)).toBe(false)
    const 少边 = { ...基, 边: [] }
    expect(同内容(基, 少边)).toBe(false)
    const 多文字 = { ...基, 文字: [...基.文字, 造文字("t9")] }
    expect(同内容(基, 多文字)).toBe(false)
  })

  test("端点接法变了（位置都合法）⇒ 不相等", () => {
    const 基: 图文件 = {
      ...造图(),
      节点: [造节点("a"), 造节点("b"), 造节点("c")],
      边: [造边("e1", "a", "b")],
    }
    const 换头 = { ...基, 边: [{ ...基.边[0]!, 到: "c" }] }
    expect(同内容(基, 换头)).toBe(false)
  })

  test("节点顺序变化 ⇒ 不相等（按位置对齐，不是集合匹配）", () => {
    const 基: 图文件 = { ...造图(), 节点: [造节点("a"), 造节点("b")], 边: [], 文字: [] }
    const 换序: 图文件 = { ...基, 节点: [基.节点[1]!, 基.节点[0]!] }
    expect(同内容(基, 换序)).toBe(false)
  })

  test("属性顺序变化 ⇒ 不相等（属性数组按位置对齐）", () => {
    const 基: 图文件 = {
      ...造图(),
      节点: [
        造节点("a", {
          属性: [
            { 键: "金额", 值: "100 元" },
            { 键: "时间", 值: "03-04" },
          ],
        }),
      ],
      边: [],
      文字: [],
    }
    const 换序: 图文件 = {
      ...基,
      节点: [{ ...基.节点[0]!, 属性: [...基.节点[0]!.属性!].reverse() }],
    }
    expect(同内容(基, 换序)).toBe(false)
  })
})
