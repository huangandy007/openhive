import { describe, expect, test } from "bun:test"
import { 纠正大类, 采纳细类, 细类 } from "../../src/server/openhive/case-subtype"

/**
 * 细类判定（阶段 1）：只回答「这个值能不能稳定判出细类」，判不出就是 `undefined`
 * ——展示层就只显示大类。**绝不猜**：错标一次，民警会按错误的口径去查。
 *
 * 优先级：`attrs.subtype`（材料里明确写出来的）> 值形状。attrs 里的值必须落在该类
 * 白名单里，否则丢弃、回落形状（模型编一个「涉案号码」不能进展示）。
 */
describe("号码细类", () => {
  test("手机号：11 位 1[3-9] 开头；归一后带 86 前缀的 13 位也认", () => {
    expect(细类("号码", "13800000001")).toBe("手机号")
    expect(细类("号码", "19912345678")).toBe("手机号")
    // `号码归一` 剥掉开头的 `+`，`+8613800138000` 落库就是这串 13 位。
    expect(细类("号码", "8613800138000")).toBe("手机号")
    // 12 位 / 10 位都不是手机号
    expect(细类("号码", "1380000000")).toBeUndefined()
    expect(细类("号码", "138000000011")).toBeUndefined()
  })

  test("身份证：18 位要看第 7–14 位是不是真日期；15 位老证看 6 位日期", () => {
    expect(细类("号码", "110101199001011234")).toBe("身份证")
    expect(细类("号码", "11010119900101123X")).toBe("身份证")
    // 月份 13：形状像身份证，日期不成立 ⇒ 不标
    expect(细类("号码", "110101199013011234")).toBeUndefined()
    // 2 月 30 日同样不成立
    expect(细类("号码", "110101199002301234")).toBeUndefined()
    expect(细类("号码", "110101900101123")).toBe("身份证")
    expect(细类("号码", "110101901301123")).toBeUndefined()
  })

  test("固定电话：0 开头的 10–12 位", () => {
    expect(细类("号码", "057188888888")).toBe("固定电话")
    expect(细类("号码", "01088888888")).toBe("固定电话")
    // 16 位卡号不是固定电话（阶段 2 会纠正大类，这里先不标细类）
    expect(细类("号码", "6222020000000001")).toBeUndefined()
  })

  test("认不出的号码不标细类（fail-closed）", () => {
    expect(细类("号码", "110")).toBeUndefined()
    expect(细类("号码", "12345")).toBeUndefined()
  })
})

describe("账户细类", () => {
  test("银行卡：16–19 位且 Luhn 通过；Luhn 不过的同形状叫「银行账号」", () => {
    expect(细类("账户", "4111111111111111")).toBe("银行卡")
    expect(细类("账户", "6222020000000001")).toBe("银行账号")
    expect(细类("账户", "6222020000")).toBeUndefined()
  })

  test("第三方支付：邮箱形态（支付宝账号）；微信标识也算这一类的账户", () => {
    expect(细类("账户", "zhangsan@alipay.com")).toBe("第三方支付")
    expect(细类("账户", "wxid_abc123")).toBe("第三方支付")
    expect(细类("账户", "张三")).toBeUndefined()
  })
})

describe("虚拟身份细类", () => {
  test("邮箱 / QQ / 微信", () => {
    expect(细类("虚拟身份", "zhang@qq.com")).toBe("邮箱")
    expect(细类("虚拟身份", "12345678")).toBe("QQ")
    expect(细类("虚拟身份", "wxid_abc123")).toBe("微信")
    // 4 位数字太短、不像 QQ；带字母的串不是 QQ
    expect(细类("虚拟身份", "1234")).toBeUndefined()
    expect(细类("虚拟身份", "abc123456")).toBeUndefined()
    // `@qq.com` 是邮箱，不是「QQ」
    expect(细类("虚拟身份", "12345678@qq.com")).toBe("邮箱")
  })
})

describe("其他大类不做细类（阶段 1）", () => {
  test("人 / 地点 / 组织 / 车辆 / 物品 一律 undefined", () => {
    for (const 类 of ["人", "地点", "组织", "车辆", "物品"]) {
      expect(细类(类, "张三")).toBeUndefined()
      expect(细类(类, "城东茶馆")).toBeUndefined()
    }
  })
})

/**
 * 大类纠正（阶段 2）：模型把 16 位卡号写成「号码」时，在入库前把大类改对。
 *
 * 只纠正**形状和现值互相矛盾**的两种，其余一律原样返回：
 * - 号码 ＋ 16–19 位数字 ⇒ 账户（18 位身份证形状除外——那本来就是号码）；
 * - 账户 ＋ 身份证形状 ⇒ 号码。
 * Luhn 不参与判断方向（卡号自检不过也还是账号），只影响纠正后的细类。
 */
describe("纠正大类", () => {
  test("号码 ＋ 16–19 位数字 ⇒ 账户（Luhn 通不通过都算）", () => {
    expect(纠正大类("号码", "6222020000000001")).toBe("账户")
    expect(纠正大类("号码", "4111111111111111")).toBe("账户")
    expect(纠正大类("号码", "6222020000000001234")).toBe("账户")
  })

  test("号码 ＋ 身份证形状 => 号码（不因 18 位就判成账户）", () => {
    expect(纠正大类("号码", "110101199001011234")).toBe("号码")
    expect(纠正大类("号码", "11010119900101123X")).toBe("号码")
    expect(纠正大类("号码", "110101900101123")).toBe("号码")
  })

  test("账户 ＋ 身份证形状 ⇒ 号码", () => {
    expect(纠正大类("账户", "110101199001011234")).toBe("号码")
    expect(纠正大类("账户", "110101900101123")).toBe("号码")
  })

  test("位数不在窗口内、日期不成立的 18 位数都不动", () => {
    // 15 位：不是 16–19 位窗口
    expect(纠正大类("号码", "622202000000000")).toBe("号码")
    // 20 位：超出窗口（不猜）
    expect(纠正大类("号码", "62220200000000012345")).toBe("号码")
    // 18 位但生日位置不是真日期 ⇒ 不是身份证，按卡号纠正
    expect(纠正大类("号码", "622202000000000012")).toBe("账户")
    expect(纠正大类("号码", "110101199013011234")).toBe("账户")
  })

  test("三类之外的大类、以及对得上的值，一律原样返回", () => {
    expect(纠正大类("号码", "13800000001")).toBe("号码")
    expect(纠正大类("账户", "6222020000000001")).toBe("账户")
    expect(纠正大类("虚拟身份", "6222020000000001")).toBe("虚拟身份")
    expect(纠正大类("人", "6222020000000001")).toBe("人")
    expect(纠正大类("地点", "城东茶馆")).toBe("地点")
  })

  test("人名的组织后缀 ⇒ 组织；其余人原样", () => {
    expect(纠正大类("人", "柏加派出所")).toBe("组织")
    expect(纠正大类("人", "某某村委会")).toBe("组织")
    expect(纠正大类("人", "某某公司")).toBe("组织")
    expect(纠正大类("人", "某某林业局")).toBe("组织")
    expect(纠正大类("人", "张三")).toBe("人")
    // 裸「局 / 所 / 院」不参与：会把「王局」「王所」「X 院」这类人名误改。
    expect(纠正大类("人", "王局")).toBe("人")
    expect(纠正大类("人", "王所")).toBe("人")
    expect(纠正大类("人", "李院")).toBe("人")
  })

  test("组织后缀只作用于「人」；别的类型原样返回", () => {
    expect(纠正大类("地点", "柏加派出所")).toBe("地点")
    expect(纠正大类("组织", "柏加派出所")).toBe("组织")
    expect(纠正大类("物品", "某某公司")).toBe("物品")
  })
})

describe("细类优先级：形状确定时不让模型/原文盖掉", () => {
  test("形状判得出 ⇒ 以形状为准", () => {
    // 11 位手机号形状，材料里写着「固定电话」也压不过形状：模型给的类别没有原文核对机制，
    // 让它盖掉确定性结论，等于把「模型说的类型」又变成权威（正是 `纠正大类` 要治的病）。
    expect(细类("号码", "13800000001", { subtype: "固定电话" })).toBe("手机号")
    expect(细类("账户", "6222020000000001", { subtype: "银行卡" })).toBe("银行账号")
  })

  test("形状判不出 ⇒ 用材料里写的（本类白名单内）", () => {
    // 10 位账号：16–19 位的卡号规则管不到，材料写着「支付宝账号」才判得出是第三方支付
    expect(细类("账户", "1234567890", { subtype: "第三方支付" })).toBe("第三方支付")
    expect(细类("号码", "4001234567", { subtype: "固定电话" })).toBe("固定电话")
  })

  test("越界的细类（不在白名单 / 不是字符串）一律丢弃", () => {
    // 形状也认不出 ⇒ 仍然 undefined，不因为 attrs 里有个值就冒出来
    expect(细类("号码", "4001234567", { subtype: "涉案号码" })).toBeUndefined()
    expect(细类("号码", "4001234567", { subtype: 123 })).toBeUndefined()
    // 白名单是按大类分的：号码的细类不能写到账户上，反之亦然
    expect(细类("账户", "1234567890", { subtype: "手机号" })).toBeUndefined()
    // 人 这类没有白名单，attrs 里写什么都不采信
    expect(细类("人", "张三", { subtype: "手机号" })).toBeUndefined()
  })

  // jsonb 列在不同驱动上读回的形状不一致（PGlite 给字符串、bun-sql 可能给对象），
  // 调用方直接把裸列传进来，这里必须两种都认——否则「材料里写了细类」在产品上恒不生效。
  test("attrs 是 JSON 文本时也要读到 subtype", () => {
    expect(细类("号码", "4001234567", '{"subtype":"固定电话"}')).toBe("固定电话")
  })

  test("attrs 是坏 JSON / 数字 / null ⇒ 当作没有 attrs", () => {
    expect(细类("号码", "4001234567", "{坏")).toBeUndefined()
    expect(细类("号码", "4001234567", 42)).toBeUndefined()
    expect(细类("号码", "4001234567", null)).toBeUndefined()
  })
})

describe("采纳细类：只收「形状判不出 + 白名单内」的那一个", () => {
  test("形状判得出 ⇒ 不采纳，不落库", () => {
    expect(采纳细类("号码", "13800000001", "固定电话")).toBeUndefined()
    expect(采纳细类("账户", "6222020000000001", "银行卡")).toBeUndefined()
  })

  test("形状判不出 + 本类白名单内 ⇒ 采纳", () => {
    expect(采纳细类("账户", "1234567890", "第三方支付")).toBe("第三方支付")
    expect(采纳细类("号码", "4001234567", "固定电话")).toBe("固定电话")
  })

  test("越界 / 非字符串 / 无白名单的大类 ⇒ 不采纳", () => {
    expect(采纳细类("账户", "1234567890", "涉案账户")).toBeUndefined()
    expect(采纳细类("账户", "1234567890", 123)).toBeUndefined()
    expect(采纳细类("账户", "1234567890", undefined)).toBeUndefined()
    expect(采纳细类("人", "张三", "手机号")).toBeUndefined()
  })
})
