  test("粗类规则（无词）的命中与字段都是 null", () => {
    const r = 判定用途({ 备注: "", 交易类型: "支付账户对支付账户转账" })
    expect(r.依据.规则).toBe("转账.转账")
    expect(r.依据.命中).toBeNull()
    expect(r.依据.字段).toBeNull()
  })

  test("纯函数：同一输入两次结果相同", () => {
    const 甲 = 判定用途({ 备注: "美宜佳便利店消费" })
    const 乙 = 判定用途({ 备注: "美宜佳便利店消费" })
    expect(甲).toEqual(乙)
  })
