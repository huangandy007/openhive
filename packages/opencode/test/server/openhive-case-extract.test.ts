/**
 * 最终评审修复 1：准入门不管类型。
 *
 * 关系端点 / 事件参与人的类型是 `推断实体类型` 判的（只有 人 / 号码），所以「按该类型查词表」
 * 那条路上地点 / 物品词表永远不可达——「现场」会被当成人落库、「树木」会新建一条「人」实体。
 */
describe("最终评审修复 1：与类型无关的泛称闸", () => {
  test("事件参与人是地点泛称 ⇒ 不建实体、participants 保留原文、提示指名", () => {
    const 片 = "案发现场位于城东茶馆，张三在场。"
    const r = 回读(
      解析({
        实体: [{ 类型: "人", 取值: "张三" }],
        关系: [],
        事件: [{ 类型: "见面", 参与人: ["现场", "张三"], 原文: "张三在场" }],
      }),
      片,
    )
    // 「现场」的推断类型是「人」；只按人角色词表判时它会被放行并落成 type=人。
    expect(r.实体.map((项) => [项.type, 项.canonicalValue])).toEqual([["人", "张三"]])
    expect(r.事件[0]?.participants).toEqual(["现场", "张三"])
    expect(r.提示.some((话) => 话.includes("现场") && 话.includes("未建实体"))).toBe(true)
  })

  test("关系端点是物品泛称 ⇒ 整条关系跳过，不新建「树木」实体", () => {
    const 片 = "张三砍伐树木，树木归村集体所有。"
    const r = 回读(
      解析({
        实体: [{ 类型: "人", 取值: "张三" }],
        关系: [{ 类型: "持有", 从: "张三", 到: "树木", 依据: "扣押实物", 原文: "张三砍伐树木" }],
        事件: [],
      }),
      片,
    )
    expect(r.关系).toEqual([])
    expect(r.实体.map((项) => [项.type, 项.canonicalValue])).toEqual([["人", "张三"]])
    expect(r.提示.some((话) => 话.includes("树木") && 话.includes("未建实体"))).toBe(true)
  })

  test("回归：真实体不误杀（张三 / 柏加派出所 / 城东茶馆）", () => {
    const 片 = "张三到柏加派出所旁的城东茶馆。"
    const r = 回读(
      解析({
        实体: [
          { 类型: "人", 取值: "张三" },
          { 类型: "人", 取值: "柏加派出所" },
          { 类型: "地点", 取值: "城东茶馆" },
        ],
        关系: [],
        事件: [],
      }),
      片,
    )
    expect(r.实体.map((项) => `${项.type}|${项.canonicalValue}`).sort()).toEqual(
      ["人|张三", "人|柏加派出所", "地点|城东茶馆"].sort(),
    )
    expect(r.提示).toEqual([])
  })
})
