describe("回读", () => {
  test("号码：原文里有分隔符也算命中，规范值去掉分隔符", () => {
    // 关系出处必须**逐字**出现在片里（回读的第一层），所以号码放在下一句，不插在引文中间。
    const 片 = "2026年3月5日，张三向李四转账28万元。张三的号码是138-0013-8000。"
    const r = 回读(
      解析({
        实体: [
          { 类型: "人", 取值: "张三" },
          { 类型: "号码", 取值: "13800138000" },
        ],
        关系: [{ 类型: "转账", 从: "张三", 到: "李四", 金额原文: "28万", 原文: "张三向李四转账28万元" }],
        事件: [],
      }),
      片,
    )
    expect(r.问题).toEqual([])
    expect(r.实体.map((e) => e.canonicalValue)).toContain("13800138000")
    expect(r.关系[0]?.amount).toBe(280000)
    expect(r.关系[0]?.存疑).toBe(false)
  })

  test("编造的人名 ⇒ 丢实体、记问题（不硬猜）", () => {
    const r = 回读(解析({ ...空, 实体: [{ 类型: "人", 取值: "王五" }] }), "张三向李四转账。")
    expect(r.实体).toEqual([])
    expect(r.问题.some((s) => s.includes("王五"))).toBe(true)
  })

  test("形近人名算命中（张叁 / 张三）", () => {
    const r = 回读(解析({ ...空, 实体: [{ 类型: "人", 取值: "张三" }] }), "张叁向李四转账。")
    expect(r.实体.map((e) => e.canonicalValue)).toEqual(["张三"])
  })

  test("金额原文不在原文里 ⇒ 金额置空、标存疑、记问题", () => {
    const r = 回读(
      解析({
        ...空,
        关系: [{ 类型: "转账", 从: "张三", 到: "李四", 金额原文: "28万", 原文: "张三向李四转账" }],
      }),
      "张三向李四转账。",
    )
    expect(r.关系[0]?.amount).toBeNull()
    expect(r.关系[0]?.存疑).toBe(true)
    expect(r.问题.length).toBe(1)
  })

  test("出处整句不在这一片 ⇒ 整条事实丢弃（连引用都没有，不能留）", () => {
    const r = 回读(
      解析({ ...空, 事件: [{ 类型: "见面", 参与人: ["张三"], 原文: "另一段原文" }] }),
      "张三向李四转账。",
    )
    expect(r.事件).toEqual([])
    expect(r.问题.length).toBe(1)
  })

  test("非数据直记关系缺依据 ⇒ 丢弃（库里 CHECK 会拒，不能等到事务里炸）", () => {
    const r = 回读(
      解析({ ...空, 关系: [{ 类型: "同案", 从: "张三", 到: "李四", 原文: "张三与李四同案" }] }),
      "张三与李四同案。",
    )
    expect(r.关系).toEqual([])
    expect(r.问题.some((s) => s.includes("依据"))).toBe(true)
  })

  test("关系和事件里的角色自动补成实体（号码按数字判）", () => {
    const r = 回读(
      解析({
        实体: [],
        关系: [{ 类型: "通话", 从: "13800138000", 到: "13900139000", 原文: "13800138000 呼叫 13900139000" }],
        事件: [],
      }),
      "13800138000 呼叫 13900139000",
    )
    expect(r.实体.map((e) => e.type)).toEqual(["号码", "号码"])
  })

  test("时间原文认不出 ⇒ 时间置空、标存疑", () => {
    const r = 回读(
      解析({ ...空, 事件: [{ 类型: "见面", 时间原文: "某天下午", 参与人: ["张三"], 原文: "张三某天下午见面" }] }),
      "张三某天下午见面",
    )
    expect(r.事件[0]?.occurredAt).toBeNull()
    expect(r.事件[0]?.存疑).toBe(true)
  })

  test("缺失金额只进提示、不进问题也不进须改正（合法缺失不是模型错误）", () => {
    const r = 回读(
      解析({ ...空, 关系: [{ 类型: "转账", 从: "张三", 到: "李四", 原文: "张三向李四转账" }] }),
      "张三向李四转账。",
    )
    expect(r.问题).toEqual([])
    expect(r.提示.length).toBe(1)
    expect(r.须改正).toEqual([])
  })

  test("编造的实体进须改正（模型能改，值得重试）", () => {
    const r = 回读(解析({ ...空, 实体: [{ 类型: "人", 取值: "王五" }] }), "张三向李四转账。")
    expect(r.须改正.some((s) => s.includes("王五"))).toBe(true)
  })

  test("时间认不出（原文里在、归一认不出）只进提示、不进须改正", () => {
    const r = 回读(
      解析({ ...空, 事件: [{ 类型: "见面", 时间原文: "2026年3月5日下午", 参与人: [], 原文: "2026年3月5日下午见面" }] }),
      "2026年3月5日下午见面。",
    )
    expect(r.事件[0]?.存疑).toBe(true)
    expect(r.问题).toEqual([])
    expect(r.提示.some((s) => s.includes("认不出"))).toBe(true)
    expect(r.须改正).toEqual([])
  })

  test("金额认不出（省略写法有歧义）只进提示、不进问题也不进须改正", () => {
    const r = 回读(
      解析({
        ...空,
        关系: [{ 类型: "转账", 从: "张三", 到: "李四", 金额原文: "三千五", 原文: "张三向李四转账三千五元" }],
      }),
      "张三向李四转账三千五元。",
    )
    expect(r.关系[0]?.amount).toBeNull()
    expect(r.关系[0]?.存疑).toBe(true)
    // 桶断言（N3-1）：这条曾经只写标题、正文不验桶，`:369` 改回 `问题.push` 也不会红。
    expect(r.问题).toEqual([])
    expect(r.提示).toEqual([expect.stringContaining("认不出")])
    expect(r.须改正).toEqual([])
  })
})

