describe("T005 · 合并节点", () => {
  test("⑧ 端点重指、出处/备注并集、来源.并入 连同并入链追加、被并入者消失、重复边保留两条", () => {
    const 图 = 空图()
    const n1 = 造节点("n1", {
      名称: "张三",
      出处: ["mat_x#Sheet1#1", "mat_x#Sheet1#2"],
      备注: "A",
      来源: { kind: "实体", 实体: "ent_1" },
      属性: [{ 键: "开户行", 值: "招行" }],
    })
    // 被并入者自己也是「合并过的节点」：它已有的 并入 链必须一起带过来（F5）
    const n2 = 造节点("n2", {
      名称: "张三丰",
      出处: ["mat_x#Sheet1#2", "mat_x#Sheet1#3"],
      备注: "B",
      来源: { kind: "实体", 实体: "ent_2", 并入: ["ent_3"] },
    })
    图.节点.push(n1, n2, 造节点("n3", { 名称: "李四" }))
    图.边.push(造边("e1", "n1", "n3"), 造边("e2", "n2", "n3"), 造边("e3", "n1", "n3"))

    const 结果 = 成功(应用操作(图, [{ 操作: "合并节点", 保留: "n1", 并入: ["n2"] }]))
    expect(结果.删除).toEqual({ 节点: 1, 边: 0 })
    expect(结果.更新).toBe(1)
    expect(结果.文档.节点.map((点) => 点.id)).toEqual(["n1", "n3"])

    const 保留 = 结果.文档.节点[0]
    expect(保留.出处).toEqual(["mat_x#Sheet1#1", "mat_x#Sheet1#2", "mat_x#Sheet1#3"])
    expect(保留.备注).toBe("A；B")
    expect(保留.属性).toEqual([{ 键: "开户行", 值: "招行" }])
    expect(保留.来源.并入).toEqual(["ent_2", "ent_3"])

    // 端点重指；重复边（同 从/到/标签/方向）不自动去重，三条都还在
    expect(结果.文档.边.map((条) => [条.id, 条.从, 条.到])).toEqual([
      ["e1", "n1", "n3"],
      ["e2", "n1", "n3"],
      ["e3", "n1", "n3"],
    ])

    const 坏 = 失败(
      应用操作(图, [{ 操作: "合并节点", 保留: "n1", 并入: ["n2", "n404"] }]),
    )
    expect(坏.话术).toContain("n404")
  })

  test("⑧b 并入为空 ⇒ 什么都不改，也不计更新（F9）", () => {
    const 图 = 空图()
    图.节点.push(造节点("n1"), 造节点("n2"))
    const 结果 = 成功(应用操作(图, [{ 操作: "合并节点", 保留: "n1", 并入: [] }]))
    expect(结果.更新).toBe(0)
    expect(结果.删除).toEqual({ 节点: 0, 边: 0 })
    expect(结果.文档.节点.map((点) => 点.id)).toEqual(["n1", "n2"])
  })
})

