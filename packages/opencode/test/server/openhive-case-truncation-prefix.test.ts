import { describe, expect, test } from "bun:test"
import {
  档案归属缺口,
  档案截断缺口,
  是档案归属缺口,
  是档案截断缺口,
} from "../../src/server/openhive/case-entity-list"

/**
 * 缺口 #18：截断 / 归属缺口文案的 `前缀` 是各句句首的**手抄副本**。
 *
 * 过滤口（`是档案截断缺口` / `是档案归属缺口`，`explore_entity` 挡掉档案版缺口用）只认
 * `前缀`；写口（`实体档案` 往 `缺口` 里 push）用 `句(...)`。两处一旦漂开，过滤**静默失效**——
 * `explore_entity` 会把只属于档案的截断句透传出去，而没有任何断言会红。
 *
 * 本文件是这次单源化重构的**特征用例**：文案逐字钉住（用户可见输出零变化），并钉住
 * 「过滤口认得出写口产出的每一句」。两条都对整个对象做，将来按同一工厂新增一类也自动被覆盖；
 * 绕过工厂手写 `前缀` 才会漏，这一点写在 `case-entity-list.ts` 的契约注释里。
 */

describe("缺口 #18：缺口文案的「前缀」与「句子」同源", () => {
  test("四类截断句逐字不变", () => {
    expect(档案截断缺口.关系数据.句(5, 9)).toBe(
      "数据说的关系只显示最近 5 条，共 9 条；关系图可按类型筛选查看邻域",
    )
    expect(档案截断缺口.关系人.句(5, 9)).toBe("人说的关系只显示最近 5 条，共 9 条")
    expect(档案截断缺口.事件.句(5, 9)).toBe(
      "事件只显示最近 5 条，共 9 条；时间线可用起止时间缩小范围",
    )
    expect(档案截断缺口.出处.句(5, 9)).toBe("出处只显示前 5 条，共 9 条")
  })

  test("两类归属缺口句逐字不变", () => {
    expect(档案归属缺口.内部往来.句(2)).toBe(
      "账户内部往来 2 条：两端都在本账户归属集内，未计入关系与对方数",
    )
    expect(档案归属缺口.归属歧义.句(2)).toBe(
      "账户归属歧义 2 条：户名对应多个账户，未归属本账户（fail-closed，不猜）",
    )
  })

  test("过滤口认得出写口产出的每一句（前缀不许与句首漂开）", () => {
    for (const [名字, 类] of Object.entries(档案截断缺口)) {
      const 句 = 类.句(5, 9)
      expect({ 名字, 句首是前缀: 句.startsWith(类.前缀) }).toEqual({ 名字, 句首是前缀: true })
      expect(是档案截断缺口(句)).toBe(true)
    }
    for (const [名字, 类] of Object.entries(档案归属缺口)) {
      const 句 = 类.句(2)
      expect({ 名字, 句首是前缀: 句.startsWith(类.前缀) }).toEqual({ 名字, 句首是前缀: true })
      expect(是档案归属缺口(句)).toBe(true)
    }
  })
})
