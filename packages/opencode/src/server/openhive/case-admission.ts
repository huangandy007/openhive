/**
 * 实体准入（阶段 B）：泛称 / 方位碎片 / 角色词不进实体表。
 *
 * ## 为什么在写入口拒，而不是事后清
 *
 * 实体表是**案卷目录**，不是数据字典。1106 案实测 59 个实体里 47 个没有任何连接，
 * 其中大量是「现场」「上侧」「村委会」这类指认不到具体对象的词。事后清理要动存量数据、
 * 还要处理引用与关系孤儿；在唯一入口 `加实体` 拒掉，新数据就不再产生这类噪声。
 *
 * ## fail-closed 的落点是「不拒」
 *
 * 只做精确词表与明确的后缀形状，不猜近义。判不出就保留——错杀一个真实体，
 * 比多一个噪声更难发现。词表是代码常量：本轮不新增配置面。
 */

const 地点泛称 = new Set([
  "现场",
  "上侧",
  "下侧",
  "内侧",
  "外侧",
  "山林",
  "山路",
  "林地",
  "本村山上",
  "自留山",
  "责任山",
  "涉案山体",
  "山上",
  "山下",
  "路边",
  "附近",
  "周围",
])

const 地点碎片后缀 = /(?:东侧|西侧|南侧|北侧|上侧|下侧|内侧|外侧|附近|周围|边上|旁边)$/
const 地点碎片最大长度 = 10

const 组织泛称 = new Set([
  "村委会",
  "居委会",
  "林业部门",
  "林业主管部门",
  "林业局",
  "银行",
  "运营商",
  "派出所",
  "鉴定机构",
  "政府部门",
  "相关单位",
  "有关单位",
])

/**
 * 组织泛称词表。**准入与 `纠正大类` 共用这一份**：`鉴定机构 / 林业部门 / 政府部门` 这类词
 * 不以机构后缀结尾，只靠 `case-subtype.ts` 的后缀表判会把它们当「人」放行（`#002-06`）。
 */
export function 是组织泛称(值: string): boolean {
  return 组织泛称.has(值)
}

const 人角色 = new Set([
  "民警",
  "被害人",
  "嫌疑人",
  "证人",
  "报案人",
  "报警人",
  "当事人",
  "家属",
  "群众",
  "工作人员",
  "负责人",
  "不明人员",
])

const 物品泛称 = new Set(["树木", "林木", "涉案树木", "树桩"])

/**
 * 返回命中原因（写进抽取 `提示`）；不是泛称返回 `undefined`。
 *
 * @param 类型 模型给出的实体大类
 * @param 规范值 `canonical_value`（已归一）
 */
export function 不可指认原因(类型: string, 规范值: string): string | undefined {
  const 值 = 规范值.trim()
  if (值 === "") return undefined
  if (类型 === "地点") {
    if (地点泛称.has(值)) return "是泛称或方位词（地点），指认不到具体地点"
    if (值.length <= 地点碎片最大长度 && 地点碎片后缀.test(值)) return "是方位碎片（地点），指认不到具体地点"
    return undefined
  }
  if (类型 === "组织" && 组织泛称.has(值)) return "是泛称（组织），指认不到具体单位"
  if (类型 === "人" && 人角色.has(值)) return "是角色词（人），不是具体的人"
  if (类型 === "物品" && 物品泛称.has(值)) return "是泛称（物品），指认不到具体物品"
  return undefined
}

/** 四张词表所属的大类；顺序只决定提示文案里写哪个类，不决定拒不拒。 */
const 泛称大类们 = ["地点", "组织", "人", "物品"] as const

/**
 * **与类型无关**的泛称闸。
 *
 * 关系端点 / 事件参与人的类型是 `推断实体类型` 判出来的（只有 人 / 号码），
 * 拿它去问 `不可指认原因` 时，地点 / 物品词表在那条路上不可达——「现场」会被当成
 * 「人」放行、「树木」会被落成「人」实体。这里把四张词表与方位后缀规则各判一次，
 * 命中即返回该原因（逐类复用 `不可指认原因`，不复制词表；`#002-06`）。
 */
export function 泛称不论类型(规范值: string): string | undefined {
  for (const 类型 of 泛称大类们) {
    const 原因 = 不可指认原因(类型, 规范值)
    if (原因 !== undefined) return 原因
  }
  return undefined
}
