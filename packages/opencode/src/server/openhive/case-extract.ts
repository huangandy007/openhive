/** 关系/事件里出现、但实体清单没列的角色：`号码归一` 认得出就按号码，否则按人。 */
function 推断实体类型(value: string): 实体类型 {
  // 不要写字符类：旧版 `/^[\d\s\-()+]+$/` 只认 ASCII 数字，全角号码与 `11010119900101123X`
  // 都会被判成「人」，实体图谱里就出现「类型=人、值是号码」的脏行。
  return 号码归一(value) !== undefined ? "号码" : "人"
}

/** `号码归一` 只认标识符；金额里的量级词单独列，用来判「抄回来的是不是一个完整的数」。 */
const 金额量级 = new Set(["万", "亿", "千", "百", "十", "仟", "佰"])
/** 负号的几种写法：抄回来的一串没带它，就说明符号被剥掉了。 */
const 负号们 = new Set(["-", "−", "－"])
const 左括号们 = new Set(["（", "("])
const 右括号们 = new Set(["）", ")"])
/**
 * 括号负数的币种前缀**连同它们之间的空白**：「（¥28万元）」「（人民币28万元）」「（ ¥28万元）」。
 * 一次剥一整段（`*`），不能只剥一层：`trimEnd()` 后若还剩 `¥`，剥掉 `¥` 又露出空白，
 * 左括号仍被藏着（第三轮复审实测的 fail-open）。
 */
const 币种与空白 = /(?:人民币|RMB|CNY|[¥￥]|\s)*$/i

/**
 * 金额原文是不是出处里**完整的一个数**（不是从中截出来的一段）。
 *
 * `文本包含` 挡不住截断：「28」在「28万元」里也包含；`amount` 于是被算成 28，且不标存疑——
 * 这正是设计 §7.4「错数字比没数字害人」要挡的那类静默错。判据只看匹配位置的左右邻
 * （空白先跳过——OCR/笔录里「28 万元」很常见）：
 * - 前一位还是数字/小数点 ⇒ 截断（「8万」从「28万」里截）；
 * - 前一位是负号，或「（…）」整个包着而抄回的一串没带括号 ⇒ 符号被剥掉（支出记成收入）；
 * - 后一位还是数字/小数点 ⇒ 截断（「28」从「28.5」里截）；
 * - 后一位是量级词 ⇒ 截断：「28」从「28万元」里截；「28万」从「28万亿元」里截——
 *   复合量级 `金额元` 本来也不认，认了就是 8 个数量级的静默错。
 *   注意「28万」对「28万元」是完整的（后一位是「元」，不是量级词）。
 * 同一串可能在原文出现多次：**任一处完整就算完整**。
 *
 * ## 括号为什么要单独判
 *
 * 括号可能被模型抄进值里（「（28万）」对原文「（28万元）」），也可能被剥掉。前者要能与
 * 带货币后缀的原文匹配上，后者要能被识别成「符号被剥掉」。所以：抄带括号时先剥掉再匹配，
 * 再用「出处这个数是否被括号包着」与「值是否带括号」比对——两边不一致就是符号丢失。
 * 判出处括号时允许 `元/圆/整/正` 这些货币后缀出现在右括号之前（「28万元）」）。
 *
 * - 出处带括号、抄回的值没带（或反过来）⇒ 符号可能被剥/被加，判不完整（fail-closed，
 *   误杀的是「共（28万元）」这类正常写法，代价是转人工而不是错数）；
 * - 左邻还要跳空白并剥币种前缀（`（¥28万元）`），右邻要跳过「元/圆/整/正」**及其后的空白**
 *   才看得见右括号（`（28万元 ）`）。
 */
function 金额完整命中(出处: string, 金额原文: string): boolean {
  const 文 = 出处.normalize("NFKC")
  // 模型抄回来的首尾空白不改变数本身（`金额元` 自己也 `trim()`）。
  const 值 = 金额原文.normalize("NFKC").trim()
  if (值 === "") return false
  const 抄带括号 = 左括号们.has(值[0] ?? "") && 右括号们.has(值[值.length - 1] ?? "")
  const 匹配值 = 抄带括号 ? 值.slice(1, -1) : 值
  if (匹配值 === "") return false
  // 字符之间允许空白，但正则按值自身长度锚定，不会跨串吞数。
  const 骨架 = 匹配值
    .split("")
    .map((字) => 字.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
    .join("\\s*")
  for (const 匹配 of 文.matchAll(new RegExp(骨架, "g"))) {
    const 起 = 匹配.index ?? 0
    const 止 = 起 + 匹配[0].length
    // 左邻：剥掉末尾的空白与币种前缀（可交替出现），然后才看是不是负号/左括号。
    // `-28万`、`−28万`、`－28万`、`负28万`、`（¥28万…）`、`（ ¥28万…）` 都是「符号被剥掉」的写法。
    const 前串 = 文.slice(0, 起).replace(币种与空白, "")
    const 前 = 前串.slice(-1)
    // 右邻：**剥掉「元/圆/整/正」与它们后面的空白**，再看是不是右括号——
    // `（28万元 ）`、`（28万元\n）` 的空白不能把括号藏起来（第二轮复审实测这里 fail-open）。
    const 后串 = 文.slice(止).trimStart()
    const 后 = 后串[0]
    const 括后 = 后串.replace(/^[元圆整正]*\s*/, "")
    const 源带括号 = 左括号们.has(前) && 右括号们.has(括后[0] ?? "")
    const 前坏 = /[0-9.]/.test(前) || 负号们.has(前) || 前 === "负" || 源带括号 !== 抄带括号
    const 后坏 = 后 !== undefined && (/[0-9.]/.test(后) || 金额量级.has(后))
    if (!前坏 && !后坏) return true
  }
  return false
}

/**
 * 标识符命中：「这段原文里有没有这个号码/账号」——**分隔符感知、且不跨串拼接**。
 *
 * 旧写法是 `出处.replace(/\D/g, "").includes(数字串(号码))`，实测把两个不相干的数拼成一个号：
 * 片「转账28万元。李四电话13800138000」配 `28138` 也通过（`#011-01` 同族）。现在按目标自身
 * 逐位放宽分隔符：目标里每位之间允许出现与 `号码归一` 共用的 `号码分隔符类`（空白、`-－—`、
 * 括号、`／/`、`·`、`.`），但**正则锚定目标的长度**，不会贪心吞进后面的字；两端的
 * `(?<![0-9A-Za-z])` / `(?![0-9A-Za-z])` 再挡一次跨串。
 */
function 标识符命中(出处: string, 值: string): boolean {
  const 目标 = 号码归一(值)
  if (目标 === undefined) return false
  const 模式 = new RegExp(
    `(?<![0-9A-Za-z])${目标
      .split("")
      .map((字) => 字.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
      .join(`${号码分隔符类}*`)}(?![0-9A-Za-z])`,
  )
  return 模式.test(出处.normalize("NFKC"))
}

/**
 * 原子值能不能在这段原文里定位到。**按类型分口径**（设计 §7.4 只允许人名形近）：
 * - 人：原文包含，或形近（「张叁 / 张三」）；
 * - 号码：只走分隔符感知的逐位比对。**不许先走 `文本包含`**——它会剥空白，
 *   「28 13800138000」于是能把 `28138` 拼出来，等于绕过逐位比对的两端锚定；
 * - 账户：`号码归一` 认得出时同样只走逐位比对；认不出时（邮箱、微信号）退回原文包含；
 * - 其余（虚拟身份、车辆、物品、地点、组织）：只认原文包含。
 */
function 命中(出处: string, 值: string, 类型: 实体类型): boolean {
  if (类型 === "人") return 文本包含(出处, 值) || 形近命中(出处, 值)
  if (类型 === "号码") return 标识符命中(出处, 值)
  if (类型 === "账户") {
    // 账户不一定是纯标识符：支付宝账号是邮箱、微信号带下划线。`号码归一` 认不出时退回原文包含；
    // 认得出（纯数字/字母数字）时仍走逐位比对，否则「28 13800138000」又能把 `28138` 拼出来。
    return 号码归一(值) !== undefined ? 标识符命中(出处, 值) : 文本包含(出处, 值)
  }
  return 文本包含(出处, 值)
}

/**
 * 「缺失即存疑」不重试：转账没金额、事件没时间是设计 §7.4 允许的输出（标存疑转人工），
 * 只进 `提示`、不进 `须改正`——否则执行器会重试并提示模型「改正」，等于诱导它编一个值。
 *
 * 两个桶的界线：**阻断＝这次没抽成，要黄；提示＝抽到了但缺值/调整了，不黄**。
 */
export function 回读(结果: 抽取结果, 片文本: string): 回读输出 {
  const 问题: string[] = []
  const 提示: string[] = []
  const 须改正: string[] = []
  /** 记一条「模型能改」的问题：既进 `问题`（落库/展示），也进 `须改正`（决定重不重试）。 */
  // 「认不出」不进这里：值已经在原文里、失败在我们的确定性归一（`parseTime` / `金额元`），
  // 模型照抄还是认不出、改抄又过不了回读，重试只会白烧调用（极端时还会让模型删掉原文时间）。
  const 记失败 = (说明: string) => {
    问题.push(说明)
    须改正.push(说明)
  }
  const 实体 = new Map<string, 实体输入>()

  const 加实体 = (类型: 实体类型, 原文值: string, 别名: readonly string[]): 实体输入 | undefined => {
    const 规范 = 实体规范值(类型, 原文值)
    if (规范 === undefined) {
      记失败(`「${原文值}」不是一个可用的${类型}`)
      return undefined
    }
    const 键 = `${类型}\u0000${规范}`
    const 既有 = 实体.get(键)
    if (既有) {
      for (const 名 of 别名) if (名 !== 规范 && !既有.aliases.includes(名)) 既有.aliases.push(名)
      return 既有
    }
    const 项: 实体输入 = { type: 类型, canonicalValue: 规范, aliases: 别名.filter((名) => 名 !== 规范) }
    实体.set(键, 项)
    return 项
  }

  for (const 项 of 结果.实体) {
    if (!命中(片文本, 项.取值, 项.类型)) {
      记失败(`实体「${项.取值}」在这段原文里找不到`)
      continue
    }
    // 别名同样是模型给的原子值，必须逐个回读（设计 §7.4「每个原子值必须能定位」）。
    // 别名通常是另一个称呼（人名），也可能是另一串号码，所以类型单独推断。
    const 别名: string[] = []
    for (const 名 of 项.别名 ?? []) {
      if (命中(片文本, 名, 推断实体类型(名))) 别名.push(名)
      else 记失败(`实体「${项.取值}」的别名「${名}」在这段原文里找不到，已丢弃`)
    }
    加实体(项.类型, 项.取值, 别名)
  }

  const 关系: 关系输入[] = []
  for (const 项 of 结果.关系) {
    if (!文本包含(片文本, 项.原文)) {
      记失败(`关系「${项.从} → ${项.到}」的出处在这段原文里找不到`)
      continue
    }
    if (!数据直记.has(项.类型) && (项.依据 === undefined || 项.依据.trim() === "")) {
      记失败(`关系「${项.从} → ${项.到}」是「${项.类型}」，但没有给认定依据`)
      continue
    }
    const 从类型 = 推断实体类型(项.从)
    const 到类型 = 推断实体类型(项.到)
    const 缺角色 = [
      { 值: 项.从, 有: 命中(项.原文, 项.从, 从类型) },
      { 值: 项.到, 有: 命中(项.原文, 项.到, 到类型) },
    ]
      .filter((角) => !角.有)
      .map((角) => 角.值)
    if (缺角色.length > 0) {
      记失败(`关系「${项.从} → ${项.到}」的${缺角色.join("、")}在出处里找不到`)
      continue
    }
    // 不写 `实体规范值(...)!`：`!` 只会把 `undefined` 静默当成真值带下去。这条守卫**当前
    // 所有调用点都走不到**（进 `加实体` 前都已过 `命中`，能走到这里的值又都能过 `实体规范值`），
    // 留它是防御性护栏。
    const 从项 = 加实体(从类型, 项.从, [])
    const 到项 = 加实体(到类型, 项.到, [])
    if (从项 === undefined || 到项 === undefined) continue

    let amount: number | null = null
    let 存疑 = false
    if (项.金额原文 !== undefined && 项.金额原文.trim() !== "") {
      if (!金额完整命中(项.原文, 项.金额原文)) {
        记失败(`关系「${项.从} → ${项.到}」的金额「${项.金额原文}」在出处里不是一个完整的数，已置空`)
        存疑 = true
      } else {
        const 值 = 金额元(项.金额原文)
        if (值 === undefined) {
          提示.push(`关系「${项.从} → ${项.到}」的金额「${项.金额原文}」认不出，已置空`)
          存疑 = true
        } else amount = 值
      }
    } else if (项.类型 === "转账") {
      // 设计 §7.4：金额缺失 ⇒ 存疑转人工，不硬猜。只对「转账」这类必须有金额的关系要求，
      // 通话/同行没有金额是常态，一律标存疑会把面板淹掉。
      提示.push(`转账关系「${项.从} → ${项.到}」没有给金额，已标存疑`)
      存疑 = true
    }

    关系.push({
      type: 项.类型,
      from: 从项.canonicalValue,
      to: 到项.canonicalValue,
      amount,
      basis: 项.依据 ?? null,
      原文: 项.原文,
      存疑,
    })
  }

  const 事件: 事件输入[] = []
  for (const 项 of 结果.事件) {
    if (!文本包含(片文本, 项.原文)) {
      记失败(`事件「${项.类型}」的出处在这段原文里找不到`)
      continue
    }
    let 存疑 = false
    let occurredRaw: string | null = null
    let occurredAt: number | null = null
    let precision: Precision | null = null
    if (项.时间原文 !== undefined && 项.时间原文.trim() !== "") {
      occurredRaw = 项.时间原文
      if (!文本包含(项.原文, 项.时间原文)) {
        记失败(`事件「${项.类型}」的时间「${项.时间原文}」在出处里找不到，已置空`)
        存疑 = true
      } else {
        const 时间 = parseTime(项.时间原文)
        if (时间 === undefined) {
          提示.push(`事件「${项.类型}」的时间「${项.时间原文}」认不出，已置空`)
          存疑 = true
        } else {
          occurredAt = 时间.seconds
          precision = 时间.precision
        }
      }
    } else {
      // 设计 §7.4：时间缺失 ⇒ 存疑转人工。
      提示.push(`事件「${项.类型}」没有给时间，已标存疑`)
      存疑 = true
    }

    const 参与人: string[] = []
    for (const 人 of 项.参与人) {
      const 人类型 = 推断实体类型(人)
      if (!命中(项.原文, 人, 人类型)) {
        记失败(`事件「${项.类型}」的参与人「${人}」在出处里找不到，已移除`)
        存疑 = true
        continue
      }
      const 项实体 = 加实体(人类型, 人, [])
      if (项实体 === undefined) continue
      参与人.push(项实体.canonicalValue)
    }

    // 事件类型过长：**不重试**（不进 `须改正`）。已经确定性截到 40 字、`提示` 有记录，
    // 让模型重来只是拿三倍调用换一个更短的短语；它和「缺失即存疑」同档——不是回读失败。
    if (项.类型.length > 40) 提示.push(`事件类型「${项.类型.slice(0, 20)}…」过长，已截到 40 字`)

    事件.push({
      type: 项.类型.slice(0, 40),
      occurredRaw,
      occurredAt,
      precision,
      participants: 参与人,
      summary: 项.简述 ?? null,
      原文: 项.原文,
      存疑,
    })
  }

  return { 实体: [...实体.values()], 关系, 事件, 问题, 提示, 须改正 }
}
