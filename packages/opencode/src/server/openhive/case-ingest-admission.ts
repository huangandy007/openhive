/**
 * 016 T013 · N8 准入结论（纯函数，无 IO）。
 *
 * 命名刻意避开既有实体泛称闸 `case-admission.ts`（那是「现场/村委会」这类词不进实体表），
 * 两者回答的不是同一个问题。
 *
 * ## 唯一口径（FR-005 / Q24）
 *
 * 准入 = 「这轮结果由**适配器**产出，原件内容与报告一致」；旁路 = 「原件直入，没有适配器
 * 参与」（四层 / 档案 / 模板路径，或历史上用过适配器但现在停用了）。旁路由前端在
 * T017 的第二时刻提示「装个技能」，所以依据要对人可读。
 *
 * `准入` 的判定条件与 brief 逐字一致：有适配器，且**没有历史报告或历史报告是同一份原件**。
 * brief 没写「有适配器但与历史 SHA 不同」这一边；这里按 fail-closed 判**旁路**并在依据里
 * 说清原因——绝不把「内容变了」说成「SHA-256 与原件一致」。
 */
export interface 准入输入 {
  本轮适配器?: { id: string; version: string }
  本轮原因码: string | null
  原件sha256: string
  /** 最近的同材料报告（本次写报告之前读到的那一行）。 */
  历史报告?: { adapterId: string | null; sourceSha256: string }
}

export interface 准入结论 {
  结论: "准入" | "旁路"
  依据: string[]
}

export function 判准入(输入: 准入输入): 准入结论 {
  // 3. 本轮已落原因码（未识别 / 值闸不过 / 失败）⇒ 不可能是适配器准入。
  //    实际到不了写报告这一步（Ruling M 只在成功时写），函数仍给出确定性结论。
  if (输入.本轮原因码 !== null && 输入.本轮原因码.trim() !== "") {
    return { 结论: "旁路", 依据: [`本轮原因码：${输入.本轮原因码}`] }
  }

  // 1. 适配器产出：首次，或与历史报告同一份原件（SHA 相同）⇒ 准入。
  if (输入.本轮适配器 !== undefined) {
    const 适配器 = `适配器 ${输入.本轮适配器.id}@${输入.本轮适配器.version}`
    if (输入.历史报告 === undefined || 输入.历史报告.sourceSha256 === 输入.原件sha256) {
      return { 结论: "准入", 依据: [适配器, "SHA-256 与原件一致"] }
    }
    return { 结论: "旁路", 依据: [适配器, "SHA-256 与历史报告不一致"] }
  }

  // 2. 四层 / 档案 / 模板：没有适配器产出，原件直入。
  const 依据 = ["无适配器产出（原件直入）"]
  const 历史适配器 = 输入.历史报告?.adapterId
  if (历史适配器 !== undefined && 历史适配器 !== null && 历史适配器 !== "") {
    依据.push(`历史报告由适配器 ${历史适配器} 产出，本轮未使用（可能已停用）`)
  }
  return { 结论: "旁路", 依据 }
}
