/**
 * 用途判定（01 §3.11）：**纯函数**，不碰库、不读时钟、不调模型。
 *
 * 为什么纯函数：① 批量路径必须零模型调用（A20 第 10 条）；② 金标准回归要能离线跑
 * 三万名行，每条用例都起库就没人愿意穷举变体；③ 判定可重算 ⇒ 改词表能全量重跑、
 * 新旧 `purpose_basis` 直接对比（01 §3.11.5）。
 */

