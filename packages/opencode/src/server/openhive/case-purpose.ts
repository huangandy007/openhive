export interface 用途依据 {
  /** 命中的规则 id（形如 `消费.停车`），永不复用。 */
  规则: string
  /** 具体命中的词；粗类规则（任一为空）为 null。 */
  命中: string | null
  /** 命中发生在哪个字段；粗类规则为 null。 */
  字段: string | null
  /** 词表版本：版本一变，旧结论才可解释、可重算（01 §3.11.5）。 */
  词表: string
}

export interface 用途 {
  一级: 一级类
  /** 只有一级是「消费」时才有二级；其余为 null。 */
  二级: 二级类 | null
  依据: 用途依据
}

export interface 判定输入 {
  备注?: string | null
  /** ①层字段事实：源文件自己声明的「交易类型」。只作前置，不进 purpose（01 §3.11.3）。 */
  交易类型?: string | null
  方向?: "收" | "付" | null
}

export interface 用途规则 {
  id: string
  优先级: number
  适用源: readonly string[]
  前置?: { 交易类型?: readonly string[]; 方向?: "收" | "付" }
  /**
   * `"备注原文"`（包含匹配）| `"备注原文全等"`（整串等于，只给填充符用）|
   * `"备注主体"` | `"备注#<键>"`。
   */
  字段: string
  任一: readonly string[]
  排除?: readonly string[]
  输出: { 一级: 一级类; 二级?: 二级类 }
  说明: string
}

/**
 * 备注分段解析（06 §2.1：`##` 分段，段内 `键：值`）。返回三样：`首段`（整段，摘要用）、
 * `主体`（首段再按 `;` 取第一段，用途规则用）、`段`（键值表，商户等②层事实用）。
 *
 * 这是**机械还原**不是解释：切段、取键值，不改一个字符（01 §6.7「预处理只做格式对齐」）。
 * 主体 = 第一个 `##` 段再按 `;` 取第一段——「零钱通作后缀」的判据要靠它（06 §6.3 修正 4）。
 */
export function 解析备注段(备注: string): { 首段: string; 主体: string; 段: Record<string, string> } {
  const 段: Record<string, string> = {}
  const 首段原 = 备注.split("##")[0] ?? ""
  // 摘要要整段（还要按 `;` 折叠，见 `case-remark-facts.ts`）；`备注：` 是导出的固定前缀，去掉。
  const 首段 = 首段原.replace(/^备注[：:]\s*/u, "").trim()
  for (const 一 of 备注.split("##")) {
    const 文本 = 一.trim()
    // 冒号必须在行首之后：`键` 为空或整段就是冒号时不算键值。
    const 冒号 = 文本.search(/[：:]/)
    if (冒号 <= 0) continue
    const 键 = 文本.slice(0, 冒号).trim()
    const 值 = 文本.slice(冒号 + 1).trim()
    // 同键重复取第一个：后出现的多半是拼接噪音，覆盖会让结果依赖拼接顺序。
    if (键 !== "" && !Object.hasOwn(段, 键)) 段[键] = 值
  }
  return { 首段, 主体: (首段原.split(";")[0] ?? "").trim(), 段 }
}

function 字段取值(字段: string, 备注: string, 段: Record<string, string>, 主体: string): string | null {
  if (字段 === "备注原文" || 字段 === "备注原文全等") return 备注
  if (字段 === "备注主体") return 主体
  if (字段.startsWith("备注#")) return 段[字段.slice("备注#".length)] ?? null
  return null
}

/**
 * 判定一张卡片（一行流水）的用途。
 *
 * 规则表必须**已按优先级升序**排好；顺序错、id 重复、类名越界由 `校验规则表` 在测试里挡，
 * 运行时不再兜（生产环境不该为「数据表被写坏」付每行一次校验的代价）。
 */
export function 判定用途(输入: 判定输入, 规则们: readonly 用途规则[] = 用途规则们): 用途 {
  const 备注 = (输入.备注 ?? "").trim()
  const 交易类型 = (输入.交易类型 ?? "").trim()
  const { 主体, 段 } = 解析备注段(备注)

  for (const 规则 of 规则们) {
    // 前置只取①层字段事实：拿不到就不猜（规则不命中，往下走）。
    if (规则.前置?.交易类型 !== undefined) {
      if (交易类型 === "" || !规则.前置.交易类型.includes(交易类型)) continue
    }
    if (规则.前置?.方向 !== undefined && 输入.方向 !== 规则.前置.方向) continue

    const 值 = 字段取值(规则.字段, 备注, 段, 主体)
    if (值 === null && 规则.任一.length > 0) continue
    // 两种匹配语义：`备注原文全等` 只给填充符（`-` / `#|#`），其余一律包含匹配。
    const 命中 =
      规则.任一.length === 0
        ? null
        : (规则.任一.find((词) =>
            规则.字段 === "备注原文全等" ? 值 === 词 : (值 ?? "").includes(词),
          ) ?? null)
    if (规则.任一.length > 0 && 命中 === null) continue
    // 排除一律看原文：同一句备注里出现「便利店」就否决「加油」，哪怕命中词在别的段。
    if (规则.排除 !== undefined && 规则.排除.some((词) => 备注.includes(词))) continue

    return {
      一级: 规则.输出.一级,
      二级: 规则.输出.二级 ?? null,
      依据: { 规则: 规则.id, 命中, 字段: 命中 === null ? null : 规则.字段, 词表: 词表版本 },
    }
  }

  // 兜底规则在表末尾无条件命中，走到这里说明规则表被改坏（例如删掉了兜底）。
  // 不抛错：入库路径上抛错会让整份材料失败，宁可交一张「未分类」给人工。
  // 依据写 `兜底.缺失`（不是 `兜底.未分类`）：审计要能区分「兜底真命中」与「表坏了」。
  return {
    一级: "未分类",
    二级: null,
    依据: { 规则: "兜底.缺失", 命中: null, 字段: null, 词表: 词表版本 },
  }
}

/**
 * 规则表准入校验（01 §3.11.4.5 四条纪律的机器化）。
 *
 * 返回问题清单，空数组 = 合规。只在测试里跑，不在热路径上跑。
 */
export function 校验规则表(规则们: readonly 用途规则[]): string[] {
  const 问题: string[] = []
  const 已见id = new Set<string>()
  const 已见优先级 = new Set<number>()
  let 上次 = -Infinity

  for (const 规则 of 规则们) {
    if (已见id.has(规则.id)) 问题.push(`规则 id 重复：${规则.id}`)
    已见id.add(规则.id)
    if (已见优先级.has(规则.优先级)) 问题.push(`优先级重复：${规则.优先级}（${规则.id}）`)
    已见优先级.add(规则.优先级)
    if (规则.优先级 <= 上次) 问题.push(`规则表未按优先级升序：${规则.id}`)
    if (规则.优先级 % 10 !== 0) 问题.push(`优先级不是 10 的倍数：${规则.id}`)
    // `适用源` 声明了就必须有值：引擎本期不按来源过滤，但空数组等于「永不适用」，
    // 会让 T5 加词后以为规则生效、实际从未命中（Minor：声明了却无人读的字段）。
    if (规则.适用源.length === 0) 问题.push(`适用源为空：${规则.id}`)
    上次 = 规则.优先级

    // 一级 12 类已有「未分类」「未识别转账」两个出口，类名写错必须当场发现。
    if (!(一级类们 as readonly string[]).includes(规则.输出.一级))
      问题.push(`一级类不在词表内：${规则.id} → ${规则.输出.一级}`)
    if (规则.输出.二级 !== undefined && !(二级类们 as readonly string[]).includes(规则.输出.二级))
      问题.push(`二级类不在词表内：${规则.id} → ${规则.输出.二级}`)
    // 非消费不能有二级：词表只给消费生长（01 §3.11.4）。
    if (规则.输出.二级 !== undefined && 规则.输出.一级 !== "消费")
      问题.push(`非消费类挂了二级：${规则.id}`)

    for (const 词 of [...规则.任一, ...(规则.排除 ?? [])]) {
      // 空词永远禁入；「单字」禁的是单个汉字（「店」「费」这类通用字），
      // 填充符 `-` / `#|#` 是精确标记、不是泛词，按单字规则拦掉会让填充符规则写不出来。
      if (词.trim() === "") 问题.push(`单字/空词禁入：${规则.id} 的空词`)
      else if (词.trim().length < 2 && /[一-鿿]/.test(词))
        问题.push(`单字/空词禁入：${规则.id} 的「${词}」`)
    }
    if (
      规则.字段 !== "备注原文" &&
      规则.字段 !== "备注原文全等" &&
      规则.字段 !== "备注主体" &&
      !(规则.字段.startsWith("备注#") && 规则.字段.length > "备注#".length)
    )
      问题.push(`未知字段：${规则.id} → ${规则.字段}`)
  }
  return 问题
}
